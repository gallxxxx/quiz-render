// Не пускает наружу сценарии с кириллицей в ИДЕНТИФИКАТОРАХ.
//
//   node tools/проверить-сценарии.mjs
//
// Зачем отдельная проверка. GitHub не принимает кириллицу в именах
// работ, шагов и переменных окружения: он не говорит, что именно не
// так, а отвечает «This run likely failed because of a workflow file
// issue» и не запускает НИЧЕГО. Ни журнала, ни шагов — пустой красный
// крест, по которому не понять причину.
//
// В этом проекте на кириллицу в именах наступали пять раз: в bash
// («РЕПО=…» стало командой), в шаге уборки релизов, в фоновой проверке,
// во вспомогательном скрипте и, наконец, в имени работы «передать» —
// причём в файле, в шапке которого про это прямо написано. Правило,
// которое помнишь, но нарушаешь, стоит превратить в проверку.
//
// Кириллица в ЗНАЧЕНИЯХ — «name», «run», комментарии, пути — законна и
// нужна: человек читает русские названия шагов. Ругаемся только на
// идентификаторы.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ПАПКА = path.join(HERE, "..", ".github", "workflows");

const НЕЛАТИНИЦА = /[^\x00-\x7F]/;

// Разбирать YAML целиком ради этого незачем: и работы, и шаги, и
// переменные — это ключи с предсказуемым отступом. Ищем их построчно,
// зато без единой зависимости.
const разобрать = (текст) => {
  const беды = [];
  const строки = текст.split(/\r?\n/);
  let вРаботах = false;
  let вПеременных = null;         // отступ блока «env:»
  строки.forEach((строка, н) => {
    const где = (что, имя) =>
      беды.push(`строка ${н + 1}: ${что} «${имя}» — кириллица в имени`);

    if (/^jobs:\s*$/.test(строка)) { вРаботах = true; return; }
    if (/^\S/.test(строка)) вРаботах = /^jobs:/.test(строка);

    // имя работы: ровно два пробела отступа внутри «jobs:»
    let m = строка.match(/^ {2}([^\s#][^:]*):\s*$/);
    if (вРаботах && m && НЕЛАТИНИЦА.test(m[1])) где("работа", m[1]);

    // идентификатор шага
    m = строка.match(/^\s*id:\s*(\S.*?)\s*$/);
    if (m && НЕЛАТИНИЦА.test(m[1])) где("шаг", m[1]);

    // переменные окружения внутри «env:»
    const отступ = строка.search(/\S/);
    if (/^\s*env:\s*$/.test(строка)) { вПеременных = отступ; return; }
    if (вПеременных !== null) {
      if (отступ <= вПеременных && строка.trim()) вПеременных = null;
      else {
        m = строка.match(/^\s*([^\s#][^:]*):\s/);
        if (m && НЕЛАТИНИЦА.test(m[1])) где("переменная", m[1]);
      }
    }

    // имя переменной оболочки: «ИМЯ=значение» в начале команды
    m = строка.match(/^\s*([A-Za-zА-Яа-яЁё_][\wА-Яа-яЁё]*)=/);
    if (m && НЕЛАТИНИЦА.test(m[1])) где("переменная оболочки", m[1]);
  });
  return беды;
};

let всего = 0;
for (const имя of fs.existsSync(ПАПКА) ? fs.readdirSync(ПАПКА) : []) {
  if (!/\.ya?ml$/i.test(имя)) continue;
  const беды = разобрать(fs.readFileSync(path.join(ПАПКА, имя), "utf8"));
  if (!беды.length) continue;
  всего += беды.length;
  console.log(`\n${имя}:`);
  for (const б of беды) console.log("   " + б);
}

if (всего) {
  console.log("");
  console.log("GitHub такой сценарий не запустит вовсе и причину не назовёт.");
  console.log("Слева от двоеточия — латиница; русское имя пиши в «name».");
  process.exit(1);
}
console.log("Сценарии в порядке: кириллицы в именах нет.");
