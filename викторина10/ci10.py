def достать_видео(задание, работа):
    """Кладёт исходную запись в папку выпуска.

    Обычно с телефона приезжает не видео, а только ЗВУК: распознаванию
    хватает его, а в готовый ролик исходник всё равно не попадает.
    Звук лежит в отдельной ветке — её мы потом удаляем, чтобы история
    репозитория не росла от каждого выпуска.
    """
    вход = os.path.join(работа, "вход")
    os.makedirs(вход, exist_ok=True)
    имя = os.path.basename(str(задание.get("имя") or "ролик.mp4"))
    цель = os.path.join(вход, имя)

    путь = задание.get("путь")
    if путь and os.path.exists(путь):
        shutil.copy2(путь, цель)
        return цель

    if задание.get("звук_путь"):
        return достать_звук(задание, вход, имя)

    if задание.get("видео_путь"):
        return достать_куски(задание, вход, имя)

    ссылка = задание.get("видео")
    if not ссылка:
        sys.exit("В задании нет ни «путь», ни «звук», ни «видео» —"
                 " нечего разбирать.")

    заголовки = {"User-Agent": "quiz10-ci"}
    # Ролик лежит в закрытом репозитории, поэтому качаем с токеном.
    # Октет-стрим обязателен: без него GitHub отдаёт описание релиза
    # в JSON, а не сам файл, и ffmpeg потом падает на «битом видео».
    токен = os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN")
    if токен and "api.github.com" in ссылка:
        заголовки["Authorization"] = "Bearer " + токен
        заголовки["Accept"] = "application/octet-stream"
    print("Качаю ролик...")
    запрос = urllib.request.Request(ссылка, headers=заголовки)
    with urllib.request.urlopen(запрос, timeout=300) as ответ, \
            io.open(цель, "wb") as ф:
        shutil.copyfileobj(ответ, ф)
    мб = os.path.getsize(цель) / 1024 / 1024
    print("   %s  (%.1f МБ)" % (имя, мб))
    if мб < 0.05:
        sys.exit("Скачалось подозрительно мало — это не ролик.")
    return цель


def из_ветки(репо, токен, ветка, файл, цель):
    """Скачивает один файл из ветки в «цель»."""
    адрес = ("https://api.github.com/repos/%s/contents/%s?ref=%s"
             % (репо, urllib.parse.quote(файл), urllib.parse.quote(ветка)))
    # Просим СЫРОЙ файл: обычный ответ приходит JSON-ом с base64 внутри
    # и обрезается на мегабайте — запись выпуска в него не влезет.
    запрос = urllib.request.Request(адрес, headers={
        "User-Agent": "quiz10-ci",
        "Authorization": "Bearer " + токен,
        "Accept": "application/vnd.github.raw",
    })
    with urllib.request.urlopen(запрос, timeout=300) as ответ, \
            io.open(цель, "ab") as ф:
        shutil.copyfileobj(ответ, ф)


def убрать_ветку(репо, токен, ветка):
    """Ветка сделала своё дело — иначе репозиторий распухнет от записей,
    которые больше никому не нужны."""
    try:
        удалить = urllib.request.Request(
            "https://api.github.com/repos/%s/git/refs/heads/%s"
            % (репо, urllib.parse.quote(ветка)),
            method="DELETE",
            headers={"User-Agent": "quiz10-ci",
                     "Authorization": "Bearer " + токен,
                     "Accept": "application/vnd.github+json"})
        urllib.request.urlopen(удалить, timeout=60)
        print("   ветку убрал")
    except Exception as e:
        print("   ветку убрать не вышло (%s) — не страшно, но лишняя" % e)


ДЕРЖИМ_ДНЕЙ = 7          # сколько живёт состояние выпуска


def прибрать_старые(репо, токен):
    """Удаляет ветки выпусков, которые давно никому не нужны.

    Держим неделю: этого с запасом хватает, чтобы вернуться и пересобрать
    выпуск другим голосом, и репозиторий при этом не копит архивы.
    """
    try:
        запрос = urllib.request.Request(
            "https://api.github.com/repos/%s/branches?per_page=100" % репо,
            headers={"User-Agent": "quiz10-ci",
                     "Authorization": "Bearer " + токен})
        with urllib.request.urlopen(запрос, timeout=60) as о:
            ветки = json.load(о)
    except Exception as e:
        print("   список веток не взялся (%s)" % e)
        return

    рубеж = time.time() - ДЕРЖИМ_ДНЕЙ * 86400
    убрано = 0
    for в in ветки:
        имя = в.get("name") or ""
        if not имя.startswith(("выпуск-", "звук-")):
            continue
        try:
            адрес = ("https://api.github.com/repos/%s/commits/%s"
                     % (репо, urllib.parse.quote(имя)))
            запрос = urllib.request.Request(адрес, headers={
                "User-Agent": "quiz10-ci",
                "Authorization": "Bearer " + токен})
            with urllib.request.urlopen(запрос, timeout=60) as о:
                когда = json.load(о)["commit"]["committer"]["date"]
            метка = time.mktime(time.strptime(когда, "%Y-%m-%dT%H:%M:%SZ"))
        except Exception:
            continue
        if метка < рубеж:
            убрать_ветку(репо, токен, имя)
            убрано += 1
    if убрано:
        print("   убрал старых веток: %d" % убрано)


def состояние_путь(ид):
    return "состояния10/%s.zip" % ид


def сохранить_состояние(ид, работа):
    """Складывает файлы выпуска в ветку — следующий шаг идёт на ДРУГОЙ машине.

    Это главное отличие от работы дома: там папка выпуска просто лежит
    и ждёт. На сборочной машине каждый запуск начинается с пустого места,
    и всё, что сделал прошлый шаг — расшифровка, раскадровка, времена, —
    исчезает вместе с машиной. Поэтому после каждого шага складываем
    папку выпуска в архив и кладём в ветку выпуска.

    Тяжёлое не берём: исходник, звук и собранное видео следующему шагу
    не нужны, а весят они всё.

    Дома ничего этого не требуется: папка выпуска никуда не денется.
    Поэтому без репозитория и токена шаг просто пропускается — иначе
    конвейер нельзя прогнать у себя и проверить до выкладки.
    """
    if not (os.environ.get("QUIZ_DATA_REPO")
            or os.environ.get("GITHUB_REPOSITORY")):
        print("Состояние не складываю: работаем дома, папка никуда не денется.")
        return
    репо, токен = где_взять()
    ветка = "выпуск-" + ид
    архив = os.path.join(работа, "_состояние.zip")
    if os.path.exists(архив):
        os.remove(архив)
    пропустить = (".wav", ".mp4", ".mov", ".mkv", ".webm", ".zip")
    with zipfile.ZipFile(архив, "w", zipfile.ZIP_DEFLATED) as z:
        for корень, папки_, файлы in os.walk(работа):
            for ф in файлы:
                полный = os.path.join(корень, ф)
                if ф.lower().endswith(пропустить):
                    continue
                z.write(полный, os.path.relpath(полный, работа))
    размер = os.path.getsize(архив) / 1024
    print("Состояние выпуска: %.0f КБ" % размер)

    завести_ветку(репо, токен, ветка)
    положить(репо, токен, ветка, состояние_путь(ид),
             io.open(архив, "rb").read(), "Состояние выпуска " + ид)
    os.remove(архив)


def вернуть_состояние(ид, работа):
    """Достаёт файлы выпуска, сделанные прошлым шагом."""
    if not (os.environ.get("QUIZ_DATA_REPO")
            or os.environ.get("GITHUB_REPOSITORY")):
        print("Состояние не забираю: работаем дома, папка выпуска на месте.")
        return
    репо, токен = где_взять()
    ветка = "выпуск-" + ид
    архив = os.path.join(работа, "_состояние.zip")
    if os.path.exists(архив):
        os.remove(архив)
    try:
        из_ветки(репо, токен, ветка, состояние_путь(ид), архив)
    except Exception as e:
        sys.exit("Не нашёл, что сделал прошлый шаг (%s).\n"
                 "Похоже, выпуск начали заново — положи ролик ещё раз." % e)
    with zipfile.ZipFile(архив) as z:
        z.extractall(работа)
    print("Вернул состояние выпуска: файлов %d"
          % len(os.listdir(os.path.join(работа, "out"))))
    os.remove(архив)


def завести_ветку(репо, токен, ветка):
    """Создаёт ветку от main, если её ещё нет."""
    try:
        запрос = urllib.request.Request(
            "https://api.github.com/repos/%s/git/ref/heads/main" % репо,
            headers={"User-Agent": "quiz10-ci",
                     "Authorization": "Bearer " + токен})
        with urllib.request.urlopen(запрос, timeout=60) as о:
            главная = json.load(о)["object"]["sha"]
        тело = json.dumps({"ref": "refs/heads/" + ветка,
                           "sha": главная}).encode()
        создать = urllib.request.Request(
            "https://api.github.com/repos/%s/git/refs" % репо,
            data=тело, method="POST",
            headers={"User-Agent": "quiz10-ci",
                     "Authorization": "Bearer " + токен,
                     "Content-Type": "application/json"})
        urllib.request.urlopen(создать, timeout=60)
    except urllib.error.HTTPError as e:
        if e.code != 422:          # 422 — ветка уже есть, это нормально
            raise


def положить(репо, токен, ветка, файл, данные, подпись, попыток=6):
    """Кладёт файл в ветку. Если он там уже есть — заменяет.

    С ПОВТОРАМИ, и это не перестраховка. GitHub время от времени
    отвечает «502 Bad Gateway» просто так: на проверке формата пар
    один такой ответ уронил весь шаг, и выпуск пропал — при том что
    работа уже была сделана. Случайный сбой чужой стороны не должен
    стоить выпуска; худшее, чем он может обойтись, — лишние секунды.

    Повторяем только то, что имеет смысл повторять: перегрузку и
    обрыв связи. «Нет прав» или «нет такой ветки» от повтора не
    исправятся, и цепляться за них незачем.
    """
    адрес = ("https://api.github.com/repos/%s/contents/%s"
             % (репо, urllib.parse.quote(файл)))
    заголовки = {"User-Agent": "quiz10-ci",
                 "Authorization": "Bearer " + токен,
                 "Content-Type": "application/json"}
    for попытка in range(1, попыток + 1):
        sha = None
        try:
            спросить = urllib.request.Request(
                адрес + "?ref=" + urllib.parse.quote(ветка), headers=заголовки)
            with urllib.request.urlopen(спросить, timeout=60) as о:
                sha = json.load(о).get("sha")
        except Exception:
            pass                    # файла нет — значит создаём новый
        тело = {"message": подпись, "branch": ветка,
                "content": base64.b64encode(данные).decode()}
        if sha:
            тело["sha"] = sha
        запрос = urllib.request.Request(адрес, data=json.dumps(тело).encode(),
                                        method="PUT", headers=заголовки)
        try:
            urllib.request.urlopen(запрос, timeout=300)
            return
        except Exception as е:
            код = getattr(е, "code", None)
            можно_ещё = код is None or код >= 500 or код == 409
            if not можно_ещё or попытка == попыток:
                raise
            # Ждём ДОЛЬШЕ, чем кажется нужным. На проверке формата пар
            # GitHub отдавал 500 подряд, а тот же запрос через минуту
            # прошёл с первого раза: икал он примерно полминуты, а
            # четыре попытки по нарастающей укладывались в восемнадцать
            # секунд — и выпуск терялся на ровном месте.
            пауза = min(45, 5 * попытка)
            подробности = ""
            try:
                подробности = е.read().decode("utf-8", "replace")[:200]
            except Exception:
                pass
            print("   GitHub ответил %s%s — жду %d с и пробую ещё раз"
                  " (%d из %d)"
                  % (код or е, (" [%s]" % подробности) if подробности else "",
                     пауза, попытка, попыток))
            time.sleep(пауза)


def где_взять():
    """Репозиторий С ДАННЫМИ и ключ к нему.

    Ветки со звуком, с роликом и с папкой выпуска лежат у данных, а не
    у кода: сборка может идти в открытом репозитории, и складывать туда
    чужой ролик нельзя. Нет своей переменной — значит, репозиторий один
    и тот же, как было раньше.
    """
    репо = (os.environ.get("QUIZ_DATA_REPO")
            or os.environ.get("GITHUB_REPOSITORY", ""))
    токен = (os.environ.get("QUIZ_DATA_TOKEN")
             or os.environ.get("GH_TOKEN") or os.environ.get("GITHUB_TOKEN"))
    if not (репо and токен):
        sys.exit("Нет токена или имени репозитория — скачать запись нечем.")
    return репо, токен


def достать_звук(задание, вход, имя):
    """Звук выпуска — то, что слушает распознавание. Обычный путь."""
    ветка = str(задание.get("звук_ветка") or "").strip()
    файл = str(задание.get("звук_путь") or "").strip()
    репо, токен = где_взять()
    if not (ветка and файл):
        sys.exit("В задании нет ветки со звуком.")

    цель = os.path.join(вход, os.path.splitext(имя)[0] + ".wav")
    print("Забираю звук из ветки «%s»..." % ветка)
    из_ветки(репо, токен, ветка, файл, цель)
    мб = os.path.getsize(цель) / 1024 / 1024
    print("   %s  (%.1f МБ)" % (os.path.basename(цель), мб))
    if мб < 0.02:
        sys.exit("Звук пустой — разбирать нечего.")
    убрать_ветку(репо, токен, ветка)
    return цель


def достать_куски(задание, вход, имя):
    """Видео целиком — запасной путь, когда звук достать не вышло.

    Страница режет ролик на куски по четыре мегабайта: один огромный
    запрос на мобильном интернете обрывается целиком, а кусок можно
    послать заново. Здесь склеиваем их обратно по порядку.
    """
    ветка = str(задание.get("видео_ветка") or "").strip()
    папка = str(задание.get("видео_путь") or "").strip()
    кусков = int(задание.get("видео_кусков") or 0)
    репо, токен = где_взять()
    if not (ветка and папка and кусков):
        sys.exit("В задании нет ветки с роликом.")

    цель = os.path.join(вход, имя)
    if os.path.exists(цель):
        os.remove(цель)            # дописываем, поэтому начинаем с чистого
    print("Забираю ролик из ветки «%s»: кусков %d" % (ветка, кусков))
    for н in range(1, кусков + 1):
        из_ветки(репо, токен, ветка, "%s/часть-%03d" % (папка, н), цель)
        print("   кусок %d из %d" % (н, кусков))
    мб = os.path.getsize(цель) / 1024 / 1024
    print("   %s  (%.1f МБ)" % (имя, мб))
    if мб < 0.05:
        sys.exit("Ролик пустой — разбирать нечего.")
    убрать_ветку(репо, токен, ветка)
    return цель


