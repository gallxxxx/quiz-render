def пары_перевод(задание):
    """Шаг 2: правки человека -> английский текст и подписи для картинок."""
    ид = задание["ид"]
    работа = папка_выпуска(ид)
    вернуть_состояние(ид, работа)
    настройки(задание, работа)

    обложки = пары_на_английский(задание.get("обложки") or [])
    вопросы = пары_на_английский(задание.get("вопросы") or [])
    концовки = пары_на_английский(задание.get("концовки") or [])
    if not вопросы:
        sys.exit("В выпуске нет ни одного вопроса.")

    # Картинку ищем по сути вопроса, а не по всей фразе: «What is her
    # zodiac sign?» -> «zodiac sign». Слова-пустышки в начале только
    # сбивают поиск.
    подписи = [пары_подпись(в) for в in вопросы]

    io.open(os.path.join(работа, "out", "_пары англ.json"), "w",
            encoding="utf-8").write(json.dumps(
                {"обложки": обложки, "вопросы": вопросы,
                 "концовки": концовки, "подписи": подписи},
                ensure_ascii=False, indent=1))
    сохранить_состояние(ид, работа)
    return записать_ответ(ид, "пары-перевод", {
        "ид": ид, "этап": "пары-перевод", "обложки": обложки,
        "вопросы": вопросы, "концовки": концовки,
        "ответы": [{"время": "", "ответ": п} for п in подписи],
    })


ПУСТЫШКИ = ("what", "is", "her", "his", "the", "a", "an", "how", "does",
            "do", "did", "she", "he", "of", "in", "on", "at", "to", "was",
            "were", "are", "you", "your", "many", "much", "which", "who")


def пары_подпись(вопрос):
    """Из вопроса — два-три слова для поиска картинки."""
    слова = re.findall(r"[A-Za-z][A-Za-z'-]*", вопрос)
    важные = [с for с in слова if с.lower() not in ПУСТЫШКИ]
    return " ".join(важные[:3]) or (слова[0] if слова else "love")


def пары_сборка(задание):
    """Шаг 3: картинки и готовый ролик."""
    ид = задание["ид"]
    работа = папка_выпуска(ид)
    вернуть_состояние(ид, работа)
    настройки(задание, работа)

    путь = os.path.join(работа, "out", "_пары англ.json")
    если_есть = json.load(io.open(путь, encoding="utf-8")) \
        if os.path.exists(путь) else {}
    вопросы = задание.get("вопросы") or если_есть.get("вопросы") or []
    обложки = задание.get("обложки") or если_есть.get("обложки") or []
    концовки = задание.get("концовки") or если_есть.get("концовки") or []
    подписи = если_есть.get("подписи") or [пары_подпись(в) for в in вопросы]
    if not вопросы:
        sys.exit("В выпуске нет ни одного вопроса.")

    картинки_выбора(задание, работа)          # свои фото из задания
    # Раскадровка нужна «картинки.py»: он берёт из неё, что искать.
    доска = os.path.join(работа, "раскадровка.txt")
    io.open(доска, "w", encoding="utf-8", newline="\r\n").write(
        "ТЕМА: %s\n" % (обложки[0] if обложки else "Couples quiz")
        + "".join("0:%02d.0 | %s\n" % (5 * (i + 1), п)
                  for i, п in enumerate(подписи)))
    шаг("ИЩУ КАРТИНКИ", "картинки.py", работа=работа)

    готовые = os.path.join(работа, "картинки", "готовые")
    выпуск = {
        "обложки": обложки,
        "вопросы": [{"текст": в,
                     "картинка": os.path.join(готовые, "%02d.png" % (i + 1))}
                    for i, в in enumerate(вопросы)],
        "концовки": концовки,
        "настройки": {
            "секунд": float((задание.get("настройки") or {}).get("секунд") or 5),
            "гамма": int((задание.get("настройки") or {}).get("гамма") or 0),
            "отсчёт": (задание.get("настройки") or {}).get("отсчёт") or "да",
        },
    }
    io.open(os.path.join(работа, "выпуск.json"), "w",
            encoding="utf-8").write(json.dumps(выпуск, ensure_ascii=False,
                                               indent=1))
    if not шаг_пар("СОБИРАЮ РОЛИК", "пары.py", работа=работа):
        sys.exit("Собрать ролик не вышло.")

    out = os.path.join(работа, "out")
    готов = [f for f in os.listdir(out) if f.lower().endswith(".mp4")]
    if not готов:
        sys.exit("Готового ролика нет.")
    готов.sort(key=lambda f: os.path.getmtime(os.path.join(out, f)),
               reverse=True)
    файл = переименовать(задание, os.path.join(out, готов[0]))
    имя_готового = os.path.basename(файл)
    print("\nГОТОВО: %s (%.1f МБ)"
          % (имя_готового, os.path.getsize(файл) / 1024 / 1024))
    if os.environ.get("GITHUB_OUTPUT"):
        io.open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8").write(
            "file=%s\nname=%s\nid=%s\n" % (файл, имя_готового, ид))
    return записать_ответ(ид, "пары-сборка", {
        "ид": ид, "этап": "пары-сборка", "файл": имя_готового,
        "английский": "\n".join(обложки + вопросы + концовки),
    })


