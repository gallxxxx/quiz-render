def шаг(название, скрипт, *args, работа=None):
    """Запускает скрипт конвейера и говорит, чем кончилось."""
    print("")
    print("=" * 54)
    print("  " + название)
    print("=" * 54)
    среда = dict(os.environ)
    if работа:
        среда["QUIZ_EPISODE"] = работа
    код = subprocess.run([sys.executable, os.path.join(HERE, скрипт)]
                         + [str(a) for a in args],
                         cwd=HERE, env=среда).returncode
    if код != 0:
        print("   шаг «%s» не удался (код %s)" % (название, код))
    return код == 0


