def расшифровка(задание):
    ид = задание["ид"]
    работа = папка_выпуска(ид)
    видео = достать_видео(задание, работа)
    настройки(задание, работа)

    if not шаг("СЛУШАЮ РУССКУЮ РЕЧЬ", "subs.py", видео, работа=работа):
        sys.exit("Распознать речь не вышло.")
    # Знаки препинания ставит нейросеть: Whisper на быстрой речи их почти
    # не ставит, а без точек в ответ влезает половина следующего пункта.
    # Нет ключа — шаг молча пропускается, ролик из-за этого не теряем.
    шаг("РАССТАВЛЯЮ ЗНАКИ", "знаки.py", работа=работа)
    шаг("ИЩУ ОТВЕТЫ", "ответы.py", работа=работа)
    if not шаг("СТАВЛЮ ТАЙМЕРЫ", "таймеры.py", "--показать", работа=работа):
        sys.exit("Таймеры расставить не вышло.")

    сохранить_состояние(ид, работа)

    файл = os.path.join(работа, "out", "ПРОВЕРЬ ТАЙМЕРЫ.txt")
    текст = прочитать(файл)
    строки = [с for с in текст.replace("\r\n", "\n").split("\n")
              if с.strip() and not с.strip().startswith("#")]
    return записать_ответ(ид, "расшифровка", {
        "ид": ид,
        "этап": "расшифровка",
        "текст": "\n".join(строки),
        "таймеров": sum(с.count(" Т ") + (1 if с.startswith("Т ") else 0)
                        for с in строки),
        "ответов": sum(с.count("«") for с in строки),
    })


def перевод(задание):
    ид = задание["ид"]
    работа = папка_выпуска(ид)
    вернуть_состояние(ид, работа)
    настройки(задание, работа)

    # Текст, который человек поправил на телефоне, кладём ровно туда,
    # откуда его читает «таймеры.py»: шапку с подсказками восстанавливаем
    # сами — в неё человек не лезет, а скрипт её пропускает по решётке.
    файл = os.path.join(работа, "out", "ПРОВЕРЬ ТАЙМЕРЫ.txt")
    io.open(файл, "w", encoding="utf-8", newline="\r\n").write(
        str(задание.get("текст") or "").strip() + "\n")

    if not шаг("ЗАБИРАЮ ПРАВКИ", "таймеры.py", "--забрать", работа=работа):
        sys.exit("Правки забрать не вышло.")
    if not шаг("ПЕРЕВОЖУ НА АНГЛИЙСКИЙ", "перевод.py", работа=работа):
        sys.exit("Перевести не вышло.")
    шаг("СОБИРАЮ СУБТИТРЫ", "перевод.py", "--собрать", работа=работа)
    if not шаг("ИЩУ ОТВЕТЫ ЗАНОВО", "ответы.py", работа=работа):
        sys.exit("Ответы найти не вышло.")
    шаг("ВОЗВРАЩАЮ ТВОИ ТАЙМЕРЫ", "таймеры.py", "--применить", работа=работа)
    шаг("СЧИТАЮ МЕТКИ ДЛЯ ОЗВУЧКИ", "паузы.py", работа=работа)

    ответы = []
    доска = os.path.join(работа, "раскадровка.txt")
    тема = ""
    for строка in прочитать(доска).replace("\r\n", "\n").split("\n"):
        с = строка.strip()
        if с.upper().startswith("ТЕМА:"):
            тема = с.split(":", 1)[1].strip()
        if not с or с.startswith("#") or "|" not in с:
            continue
        левое, правое = с.split("|", 1)
        правое = правое.split("#")[0].strip()
        if правое:
            ответы.append({"время": левое.strip(), "ответ": правое})

    сохранить_состояние(ид, работа)

    англ = свежий(работа, ".английский.txt")
    return записать_ответ(ид, "перевод", {
        "ид": ид,
        "этап": "перевод",
        "тема": тема,
        "ответы": ответы,
        "английский": прочитать(англ),
    })


def сборка(задание):
    ид = задание["ид"]
    работа = папка_выпуска(ид)
    вернуть_состояние(ид, работа)
    настройки(задание, работа)
    заголовок(задание, работа)
    картинки_выбора(задание, работа)

    if not шаг("ОЗВУЧИВАЮ", "озвучка.py", работа=работа):
        sys.exit("Озвучить не вышло.")
    шаг("СОБИРАЮ ФОН", "фон.py", работа=работа)
    # Картинки, выбранные глазами, уже лежат готовыми. Обычный подбор
    # зовём только ради пустых мест — иначе он перекачает одобренное.
    шаг("ДОБИРАЮ КАРТИНКИ", "картинки.py", работа=работа)
    if not шаг("СОБИРАЮ РОЛИК", "overlay.py", работа=работа):
        sys.exit("Собрать ролик не вышло.")

    out = os.path.join(работа, "out")
    готовые = [f for f in os.listdir(out) if f.lower().endswith(".mp4")]
    if not готовые:
        sys.exit("Готового ролика нет — что-то пошло не так.")
    готовые.sort(key=lambda f: os.path.getmtime(os.path.join(out, f)),
                 reverse=True)
    файл = переименовать(задание, os.path.join(out, готовые[0]))

    # Ветку выпуска после сборки НЕ удаляем: человек может захотеть
    # пересобрать тот же выпуск другим голосом или с другими картинками,
    # и второй раз состояния уже не будет — «положи ролик ещё раз» вместо
    # простой пересборки. Вместо этого прибираем старые ветки.
    try:
        репо, токен = где_взять()
        прибрать_старые(репо, токен)
    except SystemExit:
        pass

    имя_готового = os.path.basename(файл)
    print("\nГОТОВО: %s (%.1f МБ)"
          % (имя_готового, os.path.getsize(файл) / 1024 / 1024))
    if os.environ.get("GITHUB_OUTPUT"):
        # «id» нужен сценарию, чтобы вписать ссылку на готовый ролик
        # прямо в ответ: телефону тогда не надо искать его самому.
        io.open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8").write(
            "file=%s\nname=%s\nid=%s\n" % (файл, имя_готового, ид))
    записать_ответ(ид, "сборка", {"ид": ид, "этап": "сборка",
                                  "файл": имя_готового})
    return файл


def переименовать(задание, файл):
    """Готовому ролику — имя выпуска, а не имя фона.

    Имя собирает «overlay.py» из исходника, а на сборочной машине
    исходника уже нет: он нужен был только распознаванию и остался на
    той машине. Без этого файл называется «ГОТОВО_фон собранный.mp4»,
    и в списке роликов у человека стоит «_.mp4» — не понять, что это.
    """
    тема = str(задание.get("тема") or "").strip()
    ид = str(задание.get("ид") or "").strip()
    основа = (тема or ид or "выпуск")
    # В имени файла косые черты и двоеточия не живут, а телефон ещё и
    # показывает его целиком — оставляем только безобидное.
    основа = re.sub(r"[\\/:*?\"<>|]+", " ", основа).strip()[:60]
    дата = ид[:10] if re.match(r"^\d{4}-\d{2}-\d{2}", ид) else ""
    новое = ("%s %s.mp4" % (дата, основа)).strip()
    цель = os.path.join(os.path.dirname(файл), новое)
    if os.path.abspath(цель) != os.path.abspath(файл):
        if os.path.exists(цель):
            os.remove(цель)
        os.rename(файл, цель)
        print("Имя ролика: %s" % новое)
    return цель


def заголовок(задание, работа):
    """Строка ТЕМА в раскадровке — то, что стоит сверху кадра.

    Когда ответы найдены не по словарю марок, скрипт ставит нейтральное
    «Guess the answer». На одном ролике это незаметно, на десяти —
    одинаковая шапка у всех, поэтому даём человеку поправить её словом.
    """
    новая = str(задание.get("тема") or "").strip()
    if not новая:
        return
    доска = os.path.join(работа, "раскадровка.txt")
    if not os.path.exists(доска):
        return
    строки = io.open(доска, encoding="utf-8-sig").read() \
        .replace("\r\n", "\n").split("\n")
    for i, с in enumerate(строки):
        if с.strip().upper().startswith(("ТЕМА:", "TITLE:")):
            строки[i] = "ТЕМА: %s" % новая
            break
    else:
        строки.insert(0, "ТЕМА: %s" % новая)
    io.open(доска, "w", encoding="utf-8", newline="\r\n").write(
        "\n".join(строки))
    print("Заголовок в кадре: %s" % новая)


def картинки_выбора(задание, работа):
    """Выбранные на сайте снимки — в папку «своё», по номеру пункта.

    Номер важнее имени: подпись ответа после перевода может оказаться
    любой, а номер пункта не меняется. Так же это устроено дома —
    файл «3.jpg» встаёт на третий пункт.
    """
    свои = os.path.join(работа, "картинки", "своё")
    os.makedirs(свои, exist_ok=True)
    for i, это in enumerate(задание.get("картинки") or [], 1):
        ссылка = (это or {}).get("ссылка")
        данные = (это or {}).get("данные")
        цель = os.path.join(свои, "%d.jpg" % i)
        try:
            if данные:                      # своё фото, приехало в задании
                import base64
                io.open(цель, "wb").write(base64.b64decode(данные))
            elif ссылка:
                запрос = urllib.request.Request(
                    ссылка, headers={"User-Agent": "quiz10-ci"})
                with urllib.request.urlopen(запрос, timeout=90) as ответ, \
                        io.open(цель, "wb") as ф:
                    shutil.copyfileobj(ответ, ф)
            else:
                continue
            print("   картинка %d готова" % i)
        except Exception as e:
            print("   картинка %d не взялась: %s" % (i, e))


