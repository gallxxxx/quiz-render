# -*- coding: utf-8 -*-
r"""Викторина на 10 пунктов — сборка на чужой машине, по шагам.

    python ci10.py расшифровка задание.json
    python ci10.py перевод      задание.json
    python ci10.py сборка       задание.json

Зачем три шага, а не один. Между ними стоит человек: сначала он
проверяет, что расслышано и где встанут таймеры, потом выбирает
картинки. Дома это два блокнота посреди работы; с телефона так нельзя —
страница не может ждать, поэтому каждый шаг заканчивается файлом-ответом,
а следующий начинается новым заданием.

    расшифровка   видео -> русский текст с «Т» и ответами в кавычках
        |                 (человек правит текст, таймеры, знаки)
    перевод       правка -> английский текст и подписи ответов
        |                 (человек выбирает картинки)
    сборка        выбор  -> готовый MP4

Задание и ответ — обычные JSON рядом с репозиторием: «задания10» кладёт
страница, «ответы10» пишем мы. Всё, что относится к одному выпуску,
живёт в своей папке «выпуски10/<id>» — это тот же приём, что у папок
выпусков дома (QUIZ_EPISODE), иначе второй ролик затрёт первому и
расшифровку, и раскадровку, и картинки: имена у скачанных тиктоков
одинаковые.
"""
