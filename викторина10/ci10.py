def настройки(задание, работа):
    """Переносит выбор человека в «оформление.txt» и «голос.txt».

    Файлы настроек скрипты читают РЯДОМ С СОБОЙ, а не в папке выпуска
    (папки.here, не папки.work). Поэтому копия в папке выпуска никем не
    читается — так голос, звук и качество, выбранные на сайте, молча не
    применялись, и ролик собирался с настройками по умолчанию.

    На сборочной машине писать рядом со скриптами безопасно: она
    одноразовая, у каждого запуска своя. Дома так делать нельзя — там
    этими файлами пользуется человек, поэтому локально кладём копию в
    папку выпуска и говорим, что настройки применит только машина.
    """
    на_машине = bool(os.environ.get("GITHUB_ACTIONS"))
    куда = HERE if на_машине else работа
    выбор = задание.get("настройки") or {}
    пары = {
        "оформление.txt": {
            "СТИЛЬ": выбор.get("стиль"),
            "ЗВУК": выбор.get("звук"),
            "КАРТОЧКИ": выбор.get("карточки"),
            "ДЛИНА ТАЙМЕРА": выбор.get("длина_таймера"),
            "ТАЙМЕР": выбор.get("таймер"),
            # Ролик отсюда качают на телефон: при домашних 20 выпуск
            # весит полтораста мегабайт, при 23 — вдвое меньше, а на
            # глаз в TikTok не отличить.
            "КАЧЕСТВО": выбор.get("качество") or "23",
        },
        "голос.txt": {
            "ГОЛОС": выбор.get("голос"),
            "СКОРОСТЬ": выбор.get("скорость"),
        },
    }
    for файл, значения in пары.items():
        исходный = os.path.join(HERE, файл)
        if not os.path.exists(исходный):
            continue
        строки = io.open(исходный, encoding="utf-8-sig").read() \
            .replace("\r\n", "\n").split("\n")
        for ключ, новое in значения.items():
            if новое in (None, ""):
                continue
            найдено = False
            for i, с in enumerate(строки):
                if с.strip().upper().startswith(ключ + ":"):
                    строки[i] = "%s: %s" % (ключ, новое)
                    найдено = True
                    break
            if not найдено:
                строки.append("%s: %s" % (ключ, новое))
        io.open(os.path.join(куда, файл), "w",
                encoding="utf-8", newline="\r\n").write("\n".join(строки))
    if не_на_машине(на_машине):
        print("Настройки положены в папку выпуска: на этой машине они"
              " не применятся, чтобы не трогать домашние файлы.")
    else:
        видно = ", ".join("%s=%s" % (к, з) for з_ in пары.values()
                          for к, з in з_.items() if з)
        print("Настройки выпуска: %s" % (видно or "по умолчанию"))


def записать_ответ(ид, этап, данные):
    os.makedirs(ОТВЕТЫ, exist_ok=True)
    путь = os.path.join(ОТВЕТЫ, "%s.%s.json" % (ид, этап))
    io.open(путь, "w", encoding="utf-8").write(
        json.dumps(данные, ensure_ascii=False, indent=1))
    print("\nОтвет записан: %s" % os.path.relpath(путь, ДАННЫЕ))
    if os.environ.get("GITHUB_OUTPUT"):
        io.open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8").write(
            "answer=%s\n" % путь)
    return путь


def свежий(работа, хвост):
    """Самый свежий файл выпуска с таким окончанием."""
    out = os.path.join(работа, "out")
    если_есть = [f for f in os.listdir(out)] if os.path.isdir(out) else []
    свои = [f for f in если_есть if f.endswith(хвост)]
    if not свои:
        return None
    свои.sort(key=lambda f: os.path.getmtime(os.path.join(out, f)),
              reverse=True)
    return os.path.join(out, свои[0])


def прочитать(путь):
    return io.open(путь, encoding="utf-8-sig").read() if путь else ""


