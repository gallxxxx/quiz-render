def newest(ext):
    files = [f for f in os.listdir(OUT_DIR) if f.endswith(ext)] \
        if os.path.isdir(OUT_DIR) else []
    if not files:
        return None
    files.sort(key=lambda f: os.path.getmtime(os.path.join(OUT_DIR, f)),
               reverse=True)
    return files[0][:-len(ext)]


СЛИПЛОСЬ = 12        # столько слов подряд без точки — уже каша


def хватает_точек(words):
    """Стоит ли вообще тратить запрос.

    Считать точки на весь ролик бесполезно: во флагах их было девять
    на восемьдесят слов — вроде прилично, а на деле все девять стояли
    в конце, и середина шла двадцатью двумя словами без единого знака.
    Смотрим на самый длинный кусок без точки: если он короткий, текст
    уже нарезан и звать нейросеть незачем.
    """
    самый, текущий = 0, 0
    for w in words:
        текущий += 1
        if w["w"].rstrip("\"'»)").endswith(tuple(КОНЕЦ)):
            самый = max(самый, текущий)
            текущий = 0
    return max(самый, текущий) < СЛИПЛОСЬ


