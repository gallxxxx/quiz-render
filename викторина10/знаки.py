ПАРА = re.compile(r'"n"\s*:\s*(\d+)\s*,\s*"[^"]{1,12}"\s*:\s*"([^"]{1,40})"')


def разобрать(ответ, сколько):
    """Из ответа модели — пары (номер слова, знак).

    Нарочно НЕ разбираем JSON целиком. Модели возвращают то объект
    {"знаки": [...]}, то голый массив [...], то текст в ```-рамке, то
    обрывок — оборванный на середине ответ всё равно наполовину годится.
    Строгий json.loads на всём этом спотыкался, и живой ролик получал
    «OpenRouter ответил не по формату», хотя знаки в ответе были.
    Поэтому ищем пары «номер + знак» прямо в тексте.
    """
    выбор = (ответ.get("choices") or [{}])[0]
    msg = выбор.get("message") or {}
    body = (msg.get("content") or "").strip()
    if not body:
        # у «думающих» моделей ответ иногда целиком уезжает в reasoning
        body = str(msg.get("reasoning") or "").strip()
    пары = []
    for m in ПАРА.finditer(body):
        n = int(m.group(1))
        # модель отдаёт то «.», то «. », то вовсе «"«комментарий»."» —
        # берём первый знакомый знак, остальное выбрасываем
        з = next((c for c in m.group(2) if c in СТАВИМ), "")
        if з and 1 <= n <= сколько:
            пары.append((n, з))
    return пары or None


def похоже_на_правду(пары, слов):
    """Не сломала ли модель текст. Пустая строка — всё в порядке.

    Формат бывает верным, а содержание — мусором. Распределитель
    OpenRouter однажды отдал запрос модели на 2.6 миллиарда параметров,
    и та поставила точку после КАЖДОГО слова. Если такое записать в
    расшифровку, каждое слово станет отдельным предложением: своя строка
    субтитров, своя фраза озвучки, своя пауза. Ролик после этого только
    выбросить, а понять, что случилось, по логам невозможно.
    """
    if not пары:
        return "пусто"
    if len(пары) * 2 > слов:
        return "точка почти после каждого слова"
    return ""


def под_часами(что_делать, секунд=ЖДЁМ):
    """Ждём ответ не дольше указанного, потом бросаем и идём дальше.

    У бесплатных моделей разброс дикий: dots отвечает за 7 секунд,
    nemotron-lightning молчал 601, а nex-n2.5-pro думал 1802 — полчаса —
    и вернул пустоту. Таймаут urllib тут не спасает: он считает простой
    соединения, а сервер потихоньку шлёт заголовки и в простой не
    попадает. Поэтому запрос уходит в отдельный поток; не успел —
    берём следующий сервис, а поток умрёт вместе со скриптом.
    """
    итог = {}

    def обёртка():
        try:
            итог["ок"] = что_делать()
        except BaseException as e:          # прокидываем наружу как есть
            итог["беда"] = e

    поток = threading.Thread(target=обёртка, daemon=True)
    поток.start()
    поток.join(секунд)
    if поток.is_alive():
        raise TimeoutError("молчит дольше %d с" % секунд)
    if "беда" in итог:
        raise итог["беда"]
    return итог["ок"]


КУСОК = 400          # слов за один запрос: длинные ролики режем


def спросить(слова):
    """Возвращает (пары знаков, чем расставляли). Пусто — никто не смог."""
    for пров, имя, cfg, ключ in провайдеры():
        try:
            модель = пров.pick_model(cfg, ключ)
        except (Exception, SystemExit):
            continue
        print("Спрашиваю %s (%s)..." % (cfg["имя"], модель))
        всё, сорвалось = [], False
        for начало in range(0, len(слова), КУСОК):
            часть = слова[начало:начало + КУСОК]
            нум = "\n".join("%d %s" % (i + 1, w)
                            for i, w in enumerate(часть))
            ответ, ошибка = пров.надёжно(lambda: под_часами(lambda: пров.http(
                cfg["url"] + "/chat/completions", ключ, {
                    "model": модель,
                    "temperature": 0,
                    "messages": [{"role": "system", "content": ЗАДАНИЕ},
                                 {"role": "user", "content": нум}],
                }, timeout=ЖДЁМ)), попыток=2)
            if ответ is None:
                print("   %s не ответил (%s) — беру следующего."
                      % (cfg["имя"], ошибка))
                сорвалось = True
                break
            пары = разобрать(ответ, len(часть))
            if not пары:
                print("   %s ответил не по формату — беру следующего."
                      % cfg["имя"])
                сорвалось = True
                break
            всё += [(n + начало, з) for n, з in пары]
        if сорвалось:
            continue
        беда = похоже_на_правду(всё, len(слова))
        if беда:
            print("   %s расставил ерунду (%s) — беру следующего."
                  % (cfg["имя"], беда))
            continue
        return всё, "%s (%s)" % (cfg["имя"], модель)
    return None, ""


def расставить(words, пары):
    """Вписываем знаки в слова. Порядок и времена не трогаем."""
    слова = [w["w"] for w in words]
    for n, з in пары:
        i = n - 1
        if not (0 <= i < len(слова)):
            continue
        голое = слова[i].rstrip(ВСЕ_ЗНАКИ + "…")
        if not голое:
            continue
        слова[i] = голое + з
    # с большой буквы: первое слово и каждое после точки
    новое = True
    for i, s in enumerate(слова):
        if новое and s[:1].isalpha():
            слова[i] = s[:1].upper() + s[1:]
        новое = s.rstrip("\"'»)").endswith(tuple(КОНЕЦ))
    out = []
    for w, s in zip(words, слова):
        w = dict(w)
        w["w"] = s
        out.append(w)
    return out


# --------------------- правила, которые знаем сами ---------------------
#
# Нейросеть может не ответить (нет ключа, кончился лимит, молчит), а
# Whisper ставит знаки как придётся: в живом ролике первая половина
# приехала с точками и заглавными, вторая — сплошняком строчными.
# Эти правила работают всегда и ничего не просят у сети.

ВОПРОСНЫЕ = ("какой", "какая", "какое", "какие", "какого", "какому", "каким",
             "каких", "каком", "сколько", "что", "чего", "чему", "кто",
             "кого", "кому", "где", "куда", "откуда", "когда", "почему",
             "зачем", "чей", "чья", "чьё", "чьи", "угадай", "назови")
ПЕРВЫМ_ВОПРОСНЫЕ = ("как",)          # «Как называется...» — но только первым
МАРКЕРЫ_ОТВЕТА = ("ответ", "ответы", "отвечаю")


def _голое(s):
    return re.sub(r"[^а-яёa-z0-9]", "", s.lower().replace("ё", "е"))


def предложения(слова):
    """Границы предложений по знакам в конце слов: списки номеров."""
    вышло, текущее = [], []
    for i, s in enumerate(слова):
        текущее.append(i)
        if s.rstrip("\"'»)").endswith(tuple(КОНЕЦ)):
            вышло.append(текущее)
            текущее = []
    if текущее:
        вышло.append(текущее)
    return вышло


def разделить_по_номерам(слова):
    """«...ответ голубая 7 вопрос сколько сердец...» -> два предложения.

    Ведущий сам нумерует пункты вслух, и «<цифра> вопрос» — это всегда
    начало нового. Знаков там не было ни у Whisper, ни у нейросети (в
    живом выпуске ключей не оказалось вовсе), и в ответ уезжало «голубая
    7», а дальше «кожа 9» и «антаркида сколько из». Правило простое,
    видно его невооружённым глазом, и сети для него не нужно.

    «10 вопросов на общее знание» под правило не попадает: там
    множественное число.
    """
    for i in range(1, len(слова) - 1):
        if not re.fullmatch(r"\d{1,2}", _голое(слова[i])):
            continue
        if _голое(слова[i + 1]) != "вопрос":
            continue
        for j in (i - 1, i + 1):          # закрыть прошлое и «N вопрос»
            if слова[j].rstrip("\"'»)").endswith(tuple(КОНЕЦ)):
                continue
            голое = слова[j].rstrip(ВСЕ_ЗНАКИ + "…")
            if голое:
                слова[j] = голое + "."
    return слова


def разделить_по_ответу(слова):
    """«...по цвету правильный ответ голубая» -> вопрос и ответ врозь.

    В этом формате «правильный ответ» всегда начинает новую реплику, и
    закрыть предыдущую можно не гадая. Какой знак там встанет — точка
    или вопросительный — решает уже разбор по предложениям: он видит
    вопросное слово в начале.
    """
    for i, слово in enumerate(слова):
        if i == 0 or _голое(слово) not in МАРКЕРЫ_ОТВЕТА:
            continue
        j = i - 1
        if _голое(слова[j]) in ("правильный", "верный"):   # «правильный ответ»
            j -= 1
        if j < 0 or слова[j].rstrip("\"'»)").endswith(tuple(КОНЕЦ)):
            continue
        # «Пиши ответ в комментариях» — это не объявление ответа, а
        # призыв; резать такую фразу пополам нельзя.
        if _голое(слова[i - 1]) in ("пиши", "напиши", "пишите", "свой",
                                    "твой", "жду", "знаешь"):
            continue
        голое = слова[j].rstrip(ВСЕ_ЗНАКИ + "…")
        if голое:
            слова[j] = голое + "."
    return слова


# Слова, с которых начинается концовка ролика: «сколько отгадал из
# десяти», «пиши в комментариях». Ответ до них уже кончился.
КОНЦОВКА = ("сколько", "пиши", "напиши", "подпишись", "лайк", "поставь",
            "продолжаем", "угадал", "отгадал")


def отделить_концовку(слова):
    """«...ответ Антаркида сколько из десяти» -> два предложения.

    Последний ответ ничем не закрывается: за ним не идёт ни номера
    следующего пункта, ни нового вопроса — сразу призыв к зрителю.
    В кадре из-за этого получалось «Антаркида Сколько из десяти».
    """
    for i in range(1, len(слова)):
        if _голое(слова[i]) not in КОНЦОВКА:
            continue
        j = i - 1
        if слова[j].rstrip("\"'»)").endswith(tuple(КОНЕЦ)):
            continue
        # режем только там, где до этого шёл ответ, а не посреди фразы
        if not any(_голое(слова[k]) in МАРКЕРЫ_ОТВЕТА
                   for k in range(max(0, i - 5), i)):
            continue
        голое = слова[j].rstrip(ВСЕ_ЗНАКИ + "…")
        if голое:
            слова[j] = голое + "."
    return слова


def выбросить_номера(words):
    """Убирает предложения из одной голой цифры: «2.», «5.».

    Пока идёт таймер, диктор молчит, а Whisper на музыке и тиканье
    выдумывает короткие куски — обычно как раз число. В живом выпуске
    их набралось шесть штук, и каждое становилось бы отдельной строкой
    субтитров и отдельной фразой озвучки: диктор посреди викторины
    говорил бы «два», «пять».

    Убираем только предложение ЦЕЛИКОМ состоящее из такого числа:
    ответ-число («Правильный ответ. 8.») трогать нельзя, а он всегда
    идёт следом за словом «ответ».
    """
    слова = [w["w"] for w in words]
    все = предложения(слова)
    лишние = set()

    def цифра(i):
        голое = слова[i].strip(ВСЕ_ЗНАКИ + "…" + '"«»')
        return голое if re.fullmatch(r"\d{1,2}", голое) and int(голое) <= 10 \
            else None

    for н, куски in enumerate(все):
        # 1. Предложение целиком из одной цифры.
        if len(куски) == 1 and цифра(куски[0]):
            # Это ОТВЕТ-число только тогда, когда прошлое предложение
            # кончилось словом «ответ»: «Правильный ответ. 8.» Если там
            # уже стоял ответ словом («...Ватикан.»), цифра — мусор.
            прошлое = все[н - 1] if н else None
            ответ_впереди = (прошлое is not None
                             and _голое(слова[прошлое[-1]]) in МАРКЕРЫ_ОТВЕТА)
            if not ответ_впереди:
                лишние.add(куски[0])
            continue
        # 2. Цифра, прилипшая к концу ответа: «Правильный ответ Кожа 9.»
        #    Диктор её потом читает вслух — «the answer is skin nine».
        маркер = next((n for n, i in enumerate(куски)
                       if _голое(слова[i]) in МАРКЕРЫ_ОТВЕТА), None)
        if маркер is None or len(куски) - маркер < 3:
            continue                 # после «ответ» одно слово — это и есть ответ
        if цифра(куски[-1]):
            лишние.add(куски[-1])

    if not лишние:
        return words, 0
    # знак конца предложения уходит вместе со словом — возвращаем его
    # предыдущему, иначе два предложения склеятся в одно
    оставить = []
    for n, w in enumerate(words):
        if n not in лишние:
            оставить.append(w)
            continue
        конец = слова[n].rstrip('"«»)').endswith(tuple(КОНЕЦ))
        if not (конец and оставить):
            continue
        # Если у соседа слева знак уже есть — не трогаем его. Иначе
        # точка выброшенного номера затирала вопросительный знак
        # вопроса: «На чём многие ошибаются?» становилось «...ошибаются.»
        сосед = оставить[-1]["w"]
        if сосед.rstrip('"«»)').endswith(tuple(КОНЕЦ)):
            continue
        хвост = сосед.rstrip(ВСЕ_ЗНАКИ + "…")
        if хвост:
            оставить[-1] = dict(оставить[-1],
                                w=хвост + слова[n].rstrip('"«»)')[-1])
    return оставить, len(лишние)


def причесать(words):
    """Вопрос — со знаком вопроса, ответ — с точкой, всё с заглавной.

    Просьба Вики дословно: «предложение с ответом — всегда утвердительное,
    в конце стоит точка, предложение с вопросом всегда со знаком вопроса,
    все слова с одинакового регистра, пусть будет с заглавной буквы».
    Слова тут не меняются и не переставляются — только знак в конце
    предложения и первая буква, поэтому времена остаться не могут.
    """
    слова = отделить_концовку(разделить_по_ответу(
        разделить_по_номерам([w["w"] for w in words])))
    предыдущее_про_ответ = False
    for куски in предложения(слова):
        первые = [_голое(слова[i]) for i in куски[:2]]
        есть_ответ = any(_голое(слова[i]) in МАРКЕРЫ_ОТВЕТА for i in куски)
        вопрос = (any(с in ВОПРОСНЫЕ for с in первые)
                  or (первые and первые[0] in ПЕРВЫМ_ВОПРОСНЫЕ))
        # Сам ответ часто стоит отдельным предложением: «Правильный
        # ответ. Хамелеон?» Слова «ответ» в нём уже нет, и вопросительный
        # знак от Whisper так и оставался — а ответ утвердительный.
        сам_ответ = предыдущее_про_ответ and not вопрос
        предыдущее_про_ответ = есть_ответ
        нужен = "." if (есть_ответ or сам_ответ) else ("?" if вопрос else None)
        # Последнее предложение без знака вовсе — закрываем точкой.
        последнее = слова[куски[-1]]
        if нужен is None and not последнее.rstrip("\"'»)").endswith(tuple(КОНЕЦ)):
            нужен = "."
        if нужен:
            голое = последнее.rstrip(ВСЕ_ЗНАКИ + "…")
            if голое:
                слова[куски[-1]] = голое + нужен
        # Первое слово предложения — с заглавной. Именно первое: если
        # пункт начинается с числа («10 вопросов на общее знание»),
        # большая буква не перескакивает на соседнее слово.
        первое = слова[куски[0]]
        if первое[:1].isalpha():
            слова[куски[0]] = первое[:1].upper() + первое[1:]
        # сам ответ — тоже с заглавной: в кадре все подписи одинаковые
        маркер = next((n for n, i in enumerate(куски)
                       if _голое(слова[i]) in МАРКЕРЫ_ОТВЕТА), None)
        хвост = куски[маркер + 1:] if маркер is not None else \
            (куски if сам_ответ else [])
        for i in хвост:
            if слова[i][:1].isalpha():
                слова[i] = слова[i][:1].upper() + слова[i][1:]
                break
    out = []
    for w, s in zip(words, слова):
        w = dict(w)
        w["w"] = s
        out.append(w)
    return out


def сохранить(name, words):
    """Пишем слова, плоский текст и фразы — ровно как это делает subs.py."""
    sys.path.insert(0, HERE)
    import subs
    io.open(os.path.join(OUT_DIR, name + ".слова.json"), "w",
            encoding="utf-8").write(
        json.dumps(words, ensure_ascii=False, indent=1))
    io.open(os.path.join(OUT_DIR, name + ".ru.txt"), "w",
            encoding="utf-8").write(" ".join(w["w"] for w in words))
    subs.write_phrases(subs.phrases(words),
                       os.path.join(OUT_DIR, name + ".русский.txt"))


def main():
    args = sys.argv[1:]
    всегда = "--всегда" in args or "--force" in args
    if "--кто" in args:
        i = args.index("--кто")
        if i + 1 < len(args):
            global ПОРЯДОК
            ПОРЯДОК = (args[i + 1],)

    name = newest(".слова.json")
    if not name:
        sys.exit("Нет файла «...слова.json» — сначала распознай речь.")
    path = os.path.join(OUT_DIR, name + ".слова.json")
    words = json.load(io.open(path, encoding="utf-8"))
    if not words:
        sys.exit("В расшифровке нет слов.")

    print("Ролик: %s  (слов: %d)" % (name, len(words)))
    было = sum(1 for w in words if w["w"].rstrip("\"'»)").endswith(tuple(КОНЕЦ)))

    кто = ""
    if всегда or not хватает_точек(words):
        пары, кто = спросить([w["w"] for w in words])
        if пары:
            words = расставить(words, пары)
        else:
            # Не беда: правила ниже работают и без сети, просто грубее.
            print("\nНи один сервис не ответил — расставляю по правилам.")
    else:
        print("Знаки уже расставлены — нейросеть не беспокою.")

    # Всегда, чем бы ни кончился разговор с сетью: вопрос — со знаком
    # вопроса, ответ — с точкой, начала предложений и ответы — с заглавной.
    words = причесать(words)
    words, выброшено = выбросить_номера(words)
    if выброшено:
        print("Выбросил пустых номеров: %d (Whisper насочинял их на"
              " тиканье таймера)." % выброшено)
        words = причесать(words)     # границы сдвинулись — перечитываем
    стало = sum(1 for w in words if w["w"].rstrip("\"'»)").endswith(tuple(КОНЕЦ)))
    сохранить(name, words)
    if кто:
        print("\nЗнаки расставил %s, остальное — по правилам." % кто)
    else:
        print("\nЗнаки расставлены по правилам.")
    print("Предложений было %d, стало %d." % (было, стало))
    print("Переписал: слова.json, ru.txt, русский.txt")


if __name__ == "__main__":
    main()
