def спросить_нейросеть(words):
    """Ответы и тема от нейросети. Пусто, если ключей нет или не вышло."""
    try:
        sys.path.insert(0, HERE)
        import проверить as пров
    except Exception:
        return "", []

    очередь = []
    for имя, cfg in пров.FREE.items():
        ключ = пров.key_file(cfg["ключ"]) if cfg["ключ"] else None
        if ключ:
            очередь.append((имя, cfg, ключ))
    if not очередь:
        return "", []

    # расшифровка строками со временем — модели нужно видеть секунды
    строки, кусок, начало = [], [], None
    for w in words:
        if начало is None:
            начало = w["a"]
        кусок.append(w["w"])
        if len(" ".join(кусок)) > 70:
            строки.append("%s %s" % (mmss(начало), " ".join(кусок)))
            кусок, начало = [], None
    if кусок:
        строки.append("%s %s" % (mmss(начало or 0), " ".join(кусок)))
    текст = "\n".join(строки)

    for имя, cfg, ключ in очередь:
        ответ = None
        for попытка in range(3):
            try:
                модель = пров.pick_model(cfg, ключ)
                ответ = пров.http(cfg["url"] + "/chat/completions", ключ, {
                    "model": модель,
                    "temperature": 0,
                    "messages": [{"role": "system", "content": ЗАДАНИЕ},
                                 {"role": "user", "content": текст}],
                }, timeout=180)
                break
            except Exception as e:
                # 429 бывает «слишком часто» — тогда помогает подождать.
                # Если кончилась дневная квота, ждать бесполезно: в теле
                # ответа об этом написано, и мы сразу идём к следующему.
                тело = ""
                try:
                    тело = e.read().decode("utf-8", "replace").lower()
                except Exception:
                    pass
                кончилось = ("quota" in тело or "per day" in тело
                             or "insufficient" in тело)
                if "429" in str(e) and not кончилось and попытка < 2:
                    print("   %s занят, жду %d с..." % (имя, 20 * (попытка + 1)))
                    time.sleep(20 * (попытка + 1))
                    continue
                print("   %s не ответил (%s)"
                      % (имя, "лимит на сегодня" if кончилось
                         else str(e)[:60]))
                break
        if ответ is None:
            continue
        тело = ((ответ.get("choices") or [{}])[0].get("message")
                or {}).get("content") or ""
        m = re.search(r"\{.*\}", тело, re.S)
        if not m:
            continue
        try:
            data = json.loads(m.group(0))
        except Exception:
            continue
        найдено = []
        for it in data.get("ответы") or []:
            t = str(it.get("время", "")).strip()
            имя_ответа = str(it.get("ответ", "")).strip()
            mm = re.match(r"^(\d+):(\d+(?:[.,]\d+)?)$", t)
            if mm and имя_ответа:
                найдено.append({
                    "eng": имя_ответа,
                    "t": int(mm.group(1)) * 60 + float(mm.group(2).replace(",", ".")),
                    "heard": "", "score": 1.0})
        if найдено:
            print("   %s нашёл %d ответов" % (имя, len(найдено)))
            return str(data.get("тема", "")).strip(), найдено
    return "", []


def mmss(sec):
    return "%d:%04.1f" % (int(sec // 60), sec % 60)


