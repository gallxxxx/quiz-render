"""
Находит в русской речи ответы и СЕКУНДУ, на которой их произнесли.

Запуск:  python ответы.py
         python ответы.py --окно 3   (искать сочетания до 3 слов)

Берёт <имя>.слова.json от subs.py, ищет по «словарь.txt» и пишет
«раскадровка.txt» — что и когда появится в кадре:

    ТЕМА: Name the brand
    0:03.8 | Audi
    0:07.2 | BMW

Время — конец слова плюс небольшая задержка: ответ должен выскакивать
СРАЗУ ПОСЛЕ того, как диктор его назвал, а не до.

Whisper слышит имена собственные неточно, поэтому сравнение нестрогое
(difflib): «мерседес бенс», «хёндай», «ламборджини» ловятся. Что не
поймалось — дописывается руками, вся расшифровка с временами лежит
внизу того же файла закомментированной.
"""
