def find(words, vocab, window, stop=()):
    """Скользящее окно по словам: 1, 2, 3 слова подряд против словаря.

    Окна идут от короткого к длинному, и точное совпадение сразу
    выигрывает. Иначе «Ламборджини» цеплялось бы вместе с двумя
    соседними словами и время ответа уезжало на полсекунды вперёд.
    """
    hits, taken = [], set()
    n = len(words)
    i = 0
    while i < n:
        best = None                      # (eng, size, score)
        for size in range(1, min(window, n - i) + 1):
            if not norm(words[i + size - 1]["w"]):
                continue                 # окно кончается на знаке препинания
            chunk = norm(" ".join(w["w"] for w in words[i:i + size]))
            if not chunk or chunk in stop:
                continue
            for eng, variants in vocab:
                for v in variants:
                    if chunk == v:
                        best = (eng, size, 1.0)
                        break
                    # На коротких словах нестрогое сравнение врёт:
                    # «Ни одна девочка» ловилось как Nio, «или» как Geely.
                    # Короткие марки (БМВ, Киа, ВАЗ) берём только точно.
                    if len(chunk) < FUZZY_MIN or len(v) < FUZZY_MIN:
                        continue
                    if abs(len(chunk) - len(v)) > 3:
                        continue
                    r = SequenceMatcher(None, chunk, v).ratio()
                    if r >= RATIO and (best is None or r > best[2]):
                        best = (eng, size, r)
                if best and best[2] == 1.0:
                    break
            if best and best[2] == 1.0:
                break
        if best:
            eng, size, score = best
            if eng not in taken:                 # только первое упоминание
                taken.add(eng)
                hits.append({"eng": eng, "t": words[i + size - 1]["b"],
                             "heard": " ".join(w["w"] for w in
                                               words[i:i + size]),
                             "score": score})
            i += size
        else:
            i += 1
    return hits


МАРКЕРЫ = ("ответ", "ответы", "отвечаю")     # после них звучит ответ
ХВОСТ = 4                    # сколько слов после маркера смотрим

# Слова, на которых ответ заведомо кончился. Порядковые здесь потому,
# что без знаков препинания речь идёт сплошняком: «правильный ответ
# Ватикан третий вопрос какая...» — и в кадр уезжает «Ватикан третий».
# Тот же список держит «таймеры.py»: разметка и поиск должны понимать
# текст одинаково.
СТОП_СЛОВА = ("вопрос", "лайк", "поставь", "отправь", "продолжаем",
              "напиши", "подпишись", "страна", "марка", "номер",
              "пиши", "комментариях", "комментарии", "сколько",
              "угадал", "правильных",
              "первый", "второй", "третий", "четвертый", "четвёртый",
              "пятый", "шестой", "седьмой", "восьмой", "девятый",
              "десятый", "следующий", "далее")


def после_слова_ответ(words):
    """Ответы там, где ведущий сам их называет: «Ответ. Жираф».

    Берём слова до ближайшей точки, но не больше четырёх: ответ в такой
    викторине короткий. Время — конец последнего слова ответа, пункт
    должен выскочить сразу после того, как его произнесли.
    """
    найдено = []
    i = 0
    while i < len(words):
        сырое = words[i]["w"]
        if norm(сырое) in МАРКЕРЫ:
            куски, конец = [], None
            for j in range(i + 1, min(i + 1 + ХВОСТ, len(words))):
                слово = words[j]["w"].strip()
                чистое = слово.strip(".,!?;:»«\"")
                # «Правильный ответ — Ватикан»: тире Whisper слышит
                # отдельным словом, и в кадре получалось «– Ватикан».
                if not чистое or re.sub(r"[—–\-]", "", чистое) == "":
                    continue
                if norm(чистое) in СТОП_СЛОВА:
                    break                      # пошла следующая мысль
                куски.append(чистое)
                конец = words[j]["b"]
                # Whisper часто ставит запятую там, где ведущий сделал
                # паузу: «Ответ, Фёдор Достоевский, 10 вопрос». Без
                # остановки на запятой в ответ прилипал номер следующего
                # вопроса — «Fyodor Dostoevsky 10».
                if слово.endswith((".", "!", "?", ",", ";", ":", "—", "-")):
                    break
            # Номер следующего пункта, прилипший к ответу: «Северный
            # Ледовитый 6», «Кожа 9». У ответа из нескольких слов голая
            # цифра до десяти на конце — это номер, а не ответ. Ответ,
            # который САМ число («8», «7»), не трогаем: там одно слово.
            while len(куски) > 1 and re.fullmatch(r"\d{1,2}", куски[-1]) \
                    and int(куски[-1]) <= 10:
                куски.pop()
            if куски and конец:
                найдено.append({"rus": " ".join(куски), "t": конец,
                                "heard": " ".join(куски), "score": 1.0})
                i = j if 'j' in dir() else i + 1
        i += 1
    return найдено


def английский_текст():
    """Тот самый текст, который прочитает диктор."""
    for ext in (".английский.txt", ".en.txt"):
        файлы = [f for f in os.listdir(OUT_DIR)
                 if f.endswith(ext)] if os.path.isdir(OUT_DIR) else []
        if not файлы:
            continue
        файлы.sort(key=lambda f: os.path.getmtime(os.path.join(OUT_DIR, f)),
                   reverse=True)
        текст = io.open(os.path.join(OUT_DIR, файлы[0]),
                        encoding="utf-8-sig").read()
        # в «...английский.txt» строки идут как «0:12.5 | текст»
        строки = []
        for сырая in текст.split("\n"):
            сырая = сырая.strip()
            if not сырая or сырая.startswith("#"):
                continue
            строки.append(сырая.split("|", 1)[1] if "|" in сырая else сырая)
        if строки:
            return " ".join(строки)
    return ""


def как_в_озвучке(items):
    """Подпись в кадре должна быть тем же словом, что произносит диктор.

    Подпись переводилась отдельно от текста — двумя разными запросами к
    переводчику. Слово выходило то же по смыслу, но другое по написанию:
    в озвучке и субтитрах «Hummingbird», на экране «Colibri». Хуже того,
    «озвучка.py» ищет подпись в английском тексте, чтобы узнать, КОГДА
    она прозвучала; не найдя, ставила время наугад — сразу после таймера.
    Отсюда же и слово, выскакивающее раньше своего таймера.

    Поэтому: перевели — а теперь сверяемся с текстом и берём написание
    оттуда. Порядок ответов сохраняем, ищем каждый следующий правее
    предыдущего, чтобы одинаковые слова не схлопнулись в одно место.
    """
    текст = английский_текст()
    if not текст:
        return items
    слова = re.findall(r"[A-Za-z0-9'-]+", текст)
    низ = [w.lower().strip("'-") for w in слова]

    # Запасной путь: слова сразу после «answer». Если подпись —
    # синоним, а не другое написание («Colibri» против «Hummingbird»),
    # по буквам её не узнать, зато порядок ответов в тексте тот же.
    маркеры = []
    for i, w in enumerate(низ):
        if re.sub(r"[^a-z]", "", w) in ("answer", "answers"):
            j = i + 1
            while j < len(низ) and re.sub(r"[^a-z0-9]", "", низ[j]) in (
                    "is", "the", "a", "an", "it", ""):
                j += 1
            if j < len(низ):
                маркеры.append(j)

    с = 0
    for номер, it in enumerate(items):
        подпись = (it.get("eng") or "").strip()
        if not подпись:
            continue
        if it.get("точная"):
            # Подпись снята с кавычек самого перевода — она и есть то,
            # что произносит диктор. Искать её «похожей» незачем, а
            # навредить поиск может. Только сдвигаем метку вправо.
            место = найти_подпись(низ, подпись, с)
            if место is not None:
                с = место + 1
            continue
        ключ = re.sub(r"[^a-z0-9]", "", подпись.lower().split()[0])
        if not ключ:
            continue
        лучший, счёт = None, 0.0
        for i in range(с, len(низ)):
            w = re.sub(r"[^a-z0-9]", "", низ[i])
            if not w:
                continue
            оценка = 1.0 if w == ключ else SequenceMatcher(None, ключ, w).ratio()
            if оценка > счёт:
                лучший, счёт = i, оценка
            if счёт == 1.0:
                break
        if счёт < 0.82:
            # по буквам не нашлось — берём ответ по счёту, после «answer»
            лучший = маркеры[номер] if номер < len(маркеры) else None
            if лучший is not None and лучший < с:
                лучший = None
            # Ответа в тексте может не быть вовсе: переводчик потерял
            # «кожу», и сразу за «answer» оказалось слово «Question» из
            # следующего пункта — оно и уехало в кадр восьмой подписью.
            # Служебное слово подписью не бывает: лучше оставить перевод.
            if лучший is not None and служебное(низ[лучший]):
                лучший = None
        if лучший is not None:
            # берём столько слов, сколько было в подписи: «Mariana Trench»
            сколько = len(подпись.split())
            кусок = " ".join(слова[лучший:лучший + сколько]).strip(".,!?;:")
            if кусок:
                it["eng"] = с_заглавной(кусок[:28])
            с = лучший + 1
    return items


# Слова, которые в кадре подписью быть не могут: это речь ведущего
# вокруг ответа, а не сам ответ.
СЛУЖЕБНЫЕ = {"question", "questions", "answer", "answers", "correct",
             "right", "number", "next", "and", "the", "is", "was", "in",
             "on", "of", "what", "which", "who", "how", "many", "much",
             "write", "comment", "comments", "like", "subscribe", "guess"}


def служебное(слово):
    return re.sub(r"[^a-z]", "", слово.lower()) in СЛУЖЕБНЫЕ


def найти_подпись(низ, подпись, откуда=0):
    """Где в английском тексте стоит эта подпись. None — не нашлась."""
    ключ = re.sub(r"[^a-z0-9]", "", подпись.lower().split()[0]) \
        if подпись.split() else ""
    if not ключ:
        return None
    for i in range(откуда, len(низ)):
        if re.sub(r"[^a-z0-9]", "", низ[i]) == ключ:
            return i
    return None


def из_кавычек():
    """Ответы, размеченные человеком в окне проверки.

    «таймеры.py» кладёт сюда то, что осталось в кавычках: текст ответа и
    время, когда его договорили. Ни словарь, ни нейросеть не знают, что
    ведущий считал ответом, а человек знает — поэтому это первый источник.
    Файл пишется заново при каждой правке, так что устареть не может:
    стёрли кавычки — стёрся и файл.
    """
    путь = папки.work(os.path.join("out", "_ответы из кавычек.json"))
    if not os.path.exists(путь):
        return []
    try:
        данные = json.load(io.open(путь, encoding="utf-8"))
    except Exception:
        return []
    готово = []
    for это in данные:
        текст = str(это.get("rus") or "").strip()
        if not текст:
            continue
        готово.append({"rus": текст, "t": float(это.get("t") or 0),
                       "heard": текст, "score": 1.0})
    return готово


def с_заглавной(текст):
    """Подписи в кадре — все одинаково, с большой буквы.

    Раньше в одном списке стояли «Chameleon», «blue», «mercury» и
    «antarkid»: регистр приезжал такой, каким его отдал переводчик.
    Внутренние слова не трогаем — «Mariana Trench» уже правильное.
    """
    текст = текст.strip()
    return текст[:1].upper() + текст[1:] if текст else текст


def подписи_из_перевода():
    """Английские подписи, снятые с кавычек прямо в переводе текста.

    Их кладёт «перевод.py»: то, что стояло в «ёлочках» по-русски, и то,
    что от этого осталось по-английски. Это ровно то слово, которое
    произнесёт диктор, — второй раз переводить его незачем и вредно.
    """
    путь = папки.work(os.path.join("out", "_ответы англ.json"))
    if not os.path.exists(путь):
        return {}
    try:
        данные = json.load(io.open(путь, encoding="utf-8"))
    except Exception:
        return {}
    return {str(k).strip().lower(): str(v).strip()
            for k, v in данные.items() if str(v).strip()}


def на_английский(items):
    """Русские ответы -> английские подписи. Тем же переводчиком, что текст.

    Раньше здесь звался Google напрямую, в обход очереди из «перевод.py»:
    десять слов, которые зритель читает в кадре, переводились хуже всего
    остального, даже когда рядом лежал ключ DeepL.
    """
    try:
        sys.path.insert(0, HERE)
        import перевод as пер
    except Exception:
        return items
    pairs = пер.brands()
    готовые_подписи = подписи_из_перевода()

    # марки латиницей сразу, остальное копим на один общий запрос
    готово, ждут = [], []
    for it in items:
        # Подпись, снятая с кавычек перевода, — самая надёжная: она уже
        # согласована с озвучкой. Помечаем такие, чтобы «как_в_озвучке»
        # их больше не трогала.
        своя = готовые_подписи.get(it["rus"].strip().lower())
        if своя:
            готово.append(своя)
            it["точная"] = True
            continue
        текст, _ = пер.latinize(it["rus"], pairs)
        готово.append(текст)
        if re.search(r"[а-яё]", текст, re.I):
            ждут.append(len(готово) - 1)

    if ждут:
        # Подпись в кадре — одно-два слова, и без контекста переводчик
        # гадает. Отдаём соседние ответы подсказкой: DeepL их не переводит
        # и денег за них не берёт, но учитывает.
        контекст = " ".join(готово)[:900]
        try:
            got, кто = пер.перевести([готово[i] for i in ждут],
                                     context=контекст, тихо=True)
            for i, t in zip(ждут, got):
                if t:
                    готово[i] = t
            print("   подписи перевёл %s" % кто)
        except Exception as e:
            print("   подписи перевести не вышло (%s) — оставил как есть" % e)

    for it, текст in zip(items, готово):
        # подпись в кадре короткая: режем хвост вроде «is the answer»
        текст = re.sub(r"^(the|a|an)\s+", "", текст.strip(" .!?"), flags=re.I)
        текст = без_пояснения(текст)
        # «Antarkida's response» -> «Antarkida»: переводчик делает из
        # ответа притяжательное, когда в русском рядом стояло «ответ».
        текст = re.sub(r"['’]s$", "", текст.strip())
        it["eng"] = с_заглавной(текст[:28])
    return items


def без_пояснения(текст):
    """«Ватикан (the Vatican)» -> «the Vatican».

    Переводчик иногда не переводит слово, а приписывает перевод в
    скобках. В кадр уехало русское «Ватикан» — на англоязычную
    аудиторию. Если в скобках латиница, а снаружи кириллица, берём
    скобки; если наоборот — выбрасываем скобки.
    """
    m = re.match(r"^\s*(.+?)\s*\((.+?)\)\s*$", текст)
    if not m:
        return текст
    снаружи, внутри = m.group(1), m.group(2)
    если_русское = re.search(r"[а-яё]", снаружи, re.I)
    if если_русское and not re.search(r"[а-яё]", внутри, re.I):
        return re.sub(r"^(the|a|an)\s+", "", внутри, flags=re.I)
    return снаружи


