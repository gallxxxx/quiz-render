DELAY = 0.15        # пауза после произнесённого слова, сек
RATIO = 0.80        # ниже этого сходства не считаем совпадением
FUZZY_MIN = 5       # короче — только точное совпадение
MAX_ITEMS = 10


def norm(s):
    s = s.lower().replace("ё", "е").replace("-", " ")
    s = re.sub(r"[^0-9a-zа-я ]+", "", s)
    return re.sub(r"\s+", " ", s).strip()


def load_dict():
    """Марки из словаря плюс список «НЕ» — слова, которые марками не являются.

    Нестрогое сравнение иногда попадает в обычное русское слово: «теста»
    похоже на «тесла» на 80%, и в кадр лезла Tesla, которой в ролике нет.
    Такие слова выписываются в словарь строкой «НЕ: тест, теста» и дальше
    не рассматриваются вовсе.
    """
    if not os.path.exists(DICT):
        sys.exit("Нет файла «словарь.txt»")
    out, stop = [], set()
    for raw in io.open(DICT, encoding="utf-8-sig"):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^(?:НЕ|NOT)\s*:\s*(.+)$", line, re.I)
        if m:
            for v in m.group(1).split(","):
                v = norm(v)
                if v:
                    stop.add(v)
            continue
        if "=" not in line:
            continue
        eng, rus = line.split("=", 1)
        eng = eng.strip()
        variants = {norm(eng)}
        for v in rus.split(","):
            v = norm(v)
            if v:
                variants.add(v)
        out.append((eng, sorted(variants, key=len, reverse=True)))
    if not out:
        sys.exit("В «словарь.txt» нет ни одной строки вида «Audi = ауди»")
    return out, stop


