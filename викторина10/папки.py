# -*- coding: utf-8 -*-
"""Где лежат файлы выпуска, над которым сейчас работаем.

Обычно всё в папке со скриптами: один ролик — один набор файлов
(out, раскадровка.txt, картинки, фон). Так было всегда, так и осталось.

Когда роликов несколько, каждому нужна своя папка, иначе второй затрёт
первому и субтитры, и раскадровку, и картинки — имена-то у скачанных
тиктоков одинаковые. Тогда «! СОБРАТЬ ВСЁ» заводит папку в «выпуски»
и передаёт её путь через переменную окружения QUIZ_EPISODE.

Что переезжает в папку выпуска: out, раскадровка.txt, картинки\готовые,
собранный фон. Что остаётся общим: настройки (голос.txt, оформление.txt,
словарь.txt, вырезать.txt), свои картинки, шрифты, ключ Pexels и память
о том, какие снимки и клипы уже показывали.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.environ.get("QUIZ_EPISODE") or HERE


def work(*parts):
    """Путь внутри папки этого выпуска."""
    return os.path.join(WORK, *parts)


def here(*parts):
    """Путь к общему файлу — настройке, шрифту, ключу."""
    return os.path.join(HERE, *parts)


def name():
    """Как называется выпуск — для заголовков в консоли."""
    return os.path.basename(WORK) if WORK != HERE else ""
