# -*- coding: utf-8 -*-
r"""Где в расшифровке вопрос, а где ответ на него. Решает нейросеть.

Запуск:  python разметка.py
         python разметка.py --кто gemini

Зачем. Раньше ответ искался по слову «ответ»: «Правильный ответ —
Ватикан». Но так говорят не все. Бывает просто

    Столица Таиланда?  Бангкок.
    А сколько планет в солнечной системе?  Восемь.

— ни слова «ответ», ни номеров пунктов. По такому ролику прежний
поиск не находил ничего, и в кадре оставались «???».

Что делает скрипт. Отдаёт нейросети слова ПО НОМЕРАМ и просит вернуть
только номера: с какого по какое слово идёт ответ в каждом пункте.
Сам текст она не переписывает — как и в «знаки.py», ответ приходит
списком чисел, поэтому ни слова, ни времена разъехаться не могут.

Пишет «out/_разметка ответов.json»:

    [{"с": 13, "по": 14}, {"с": 27, "по": 27}, ...]

Его читает «таймеры.py»: нашёлся файл — берёт ответы оттуда, нет —
ищет по слову «ответ», как раньше. То есть без сети всё работает
по-старому, просто хуже.
"""
import io
import json
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import папки

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = папки.work("out")
ФАЙЛ = os.path.join(OUT_DIR, "_разметка ответов.json")

ЖДЁМ = 120
МАКС_ПУНКТОВ = 12          # десять пунктов плюс запас
МАКС_СЛОВ_В_ОТВЕТЕ = 4

ЗАДАНИЕ = (
    "Это расшифровка короткой видео-викторины. Ведущий задаёт вопросы и\n"
    "сам называет ответы.\n"
    "\n"
    "Тебе дают слова по одному, каждое со своим номером. Найди ОТВЕТЫ и\n"
    "верни только номера слов — с какого по какое слово идёт ответ.\n"
    "\n"
    "ГЛАВНОЕ: слова «ответ» в ролике может не быть вовсе, и номера\n"
    "вопросов тоже могут не звучать. Вопросы могут идти подряд:\n"
    "«Столица Таиланда? Бангкок. Сколько планет в солнечной системе?\n"
    "Восемь.» Определяй по смыслу: сначала спрашивают — потом называют.\n"
    "\n"
    "Правила:\n"
    "  - ответ это ТОЛЬКО само слово-ответ: «Бангкок», «Южная Корея»,\n"
    "    «Восемь». Без «правильный ответ», без номера пункта, без\n"
    "    вопросительной части;\n"
    "  - ответ короткий: одно-два слова, редко три. Целое предложение\n"
    "    ответом не бывает;\n"
    "  - ответ из нескольких слов («Южная Корея», «Северный Ледовитый»)\n"
    "    не разрывай: «с» — первое слово, «по» — последнее;\n"
    "  - вступление и концовку («Сколько из десяти», «пиши в\n"
    "    комментариях») ответами не считай;\n"
    "  - порядок сохраняй, по одному ответу на вопрос;\n"
    "  - если на какой-то вопрос ответа не прозвучало — пропусти его,\n"
    "    не выдумывай.\n"
    "\n"
    "Ответ — строго JSON, без пояснений и без markdown:\n"
    '{"ответы": [{"с": 13, "по": 14}, {"с": 27, "по": 27}]}'
)

# Порядок тот же, что у знаков препинания: у OpenRouter в одном ключе
# десяток бесплатных моделей, Gemini держим вторым — он всегда отвечает.
ПОРЯДОК = ("openrouter", "gemini", "groq", "mistral", "ollama")
ХОЧУ_OPENROUTER = ["dots-3-note", "gemma-4 -batch", "openrouter/free", ":free"]

ПАРА = re.compile(r'"[сc]"\s*:\s*(\d+)\s*,\s*"(?:по|to)"\s*:\s*(\d+)')


def провайдеры():
    sys.path.insert(0, HERE)
    import проверить as пров
    for имя in ПОРЯДОК:
        cfg = пров.FREE.get(имя)
        if not cfg:
            continue
        cfg = dict(cfg)
        if имя == "openrouter":
            cfg["хочу"] = ХОЧУ_OPENROUTER
        ключ = пров.key_file(cfg["ключ"]) if cfg["ключ"] else None
        if cfg["ключ"] and not ключ:
            continue
        yield пров, имя, cfg, ключ


def разобрать(ответ, слов):
    """Из ответа модели — пары (с, по). Разбираем не JSON'ом, а поиском.

    Тот же приём, что в «знаки.py»: модели возвращают то объект, то
    голый массив, то текст в рамке, то обрывок. Строгий разбор на этом
    спотыкается, а пары чисел видны в любом из этих видов.
    """
    выбор = (ответ.get("choices") or [{}])[0]
    msg = выбор.get("message") or {}
    тело = (msg.get("content") or "").strip() or str(msg.get("reasoning") or "")
    куски = []
    for m in ПАРА.finditer(тело):
        с, по = int(m.group(1)), int(m.group(2))
        if not (1 <= с <= по <= слов):
            continue
        if по - с + 1 > МАКС_СЛОВ_В_ОТВЕТЕ:
            continue                      # ответом целое предложение не бывает
        куски.append({"с": с, "по": по})
    # Порядок и неперекрытие: модель иногда возвращает пункты вперемешку.
    куски.sort(key=lambda к: к["с"])
    чистые, конец = [], 0
    for к in куски:
        if к["с"] <= конец:
            continue
        чистые.append(к)
        конец = к["по"]
    return чистые[:МАКС_ПУНКТОВ]


def похоже_на_правду(куски, слов):
    """Пустая строка — всё в порядке."""
    if not куски:
        return "ничего не нашла"
    if len(куски) > МАКС_ПУНКТОВ:
        return "слишком много ответов"
    # Ответы не могут занимать половину ролика.
    занято = sum(к["по"] - к["с"] + 1 for к in куски)
    if слов and занято > слов * 0.4:
        return "в ответы записано полролика"
    return ""


def спросить(слова):
    """Возвращает (список кусков, кто разметил). Пусто — никто не смог."""
    sys.path.insert(0, HERE)
    import знаки            # у него уже есть и таймер, и надёжный вызов
    нум = "\n".join("%d %s" % (i + 1, с) for i, с in enumerate(слова))
    for пров, имя, cfg, ключ in провайдеры():
        try:
            модель = пров.pick_model(cfg, ключ)
        except (Exception, SystemExit):
            continue
        print("Спрашиваю %s (%s)..." % (cfg["имя"], модель))
        ответ, ошибка = пров.надёжно(lambda: знаки.под_часами(lambda: пров.http(
            cfg["url"] + "/chat/completions", ключ, {
                "model": модель,
                "temperature": 0,
                "messages": [{"role": "system", "content": ЗАДАНИЕ},
                             {"role": "user", "content": нум}],
            }, timeout=ЖДЁМ), ЖДЁМ), попыток=2)
        if ответ is None:
            print("   %s не ответил (%s) — беру следующего."
                  % (cfg["имя"], ошибка))
            continue
        куски = разобрать(ответ, len(слова))
        беда = похоже_на_правду(куски, len(слова))
        if беда:
            print("   %s разметил странно (%s) — беру следующего."
                  % (cfg["имя"], беда))
            continue
        return куски, "%s (%s)" % (cfg["имя"], модель)
    return [], ""


def newest(ext):
    файлы = [f for f in os.listdir(OUT_DIR) if f.endswith(ext)] \
        if os.path.isdir(OUT_DIR) else []
    if not файлы:
        return None
    файлы.sort(key=lambda f: os.path.getmtime(os.path.join(OUT_DIR, f)),
               reverse=True)
    return файлы[0][:-len(ext)]


def main():
    args = sys.argv[1:]
    if "--кто" in args:
        i = args.index("--кто")
        if i + 1 < len(args):
            global ПОРЯДОК
            ПОРЯДОК = (args[i + 1],)

    имя = newest(".слова.json")
    if not имя:
        sys.exit("Нет файла «...слова.json» — сначала распознай речь.")
    words = json.load(io.open(os.path.join(OUT_DIR, имя + ".слова.json"),
                              encoding="utf-8"))
    if not words:
        sys.exit("В расшифровке нет слов.")

    слова = [str(w.get("w") or "") for w in words]
    print("Ролик: %s  (слов: %d)" % (имя, len(слова)))
    куски, кто = спросить(слова)
    if not куски:
        # Не беда: «таймеры.py» поищет ответы по слову «ответ», как раньше.
        print("\nРазметить не вышло — ответы будут искаться по слову «ответ».")
        if os.path.exists(ФАЙЛ):
            os.remove(ФАЙЛ)       # старая разметка чужого выпуска опаснее пустоты
        return

    os.makedirs(OUT_DIR, exist_ok=True)
    io.open(ФАЙЛ, "w", encoding="utf-8").write(
        json.dumps(куски, ensure_ascii=False, indent=1))
    print("\nРазметил %s. Ответов: %d" % (кто, len(куски)))
    for к in куски:
        print("   %s" % " ".join(слова[к["с"] - 1:к["по"]]).strip(".,!?;:"))


if __name__ == "__main__":
    main()
