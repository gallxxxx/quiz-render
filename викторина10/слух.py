r"""Речь -> слова со временами, но НЕ местным Whisper.

Две двери в одну комнату:

    из_текста(текст)   — готовый текст (человек принёс свой сценарий)
    нейросетью(wav)    — запись слушает нейросеть, а не Whisper

Зачем это вообще. Местный Whisper «small» на живых роликах врал так,
что человек переписывал половину руками: «Юбитер» вместо «Юпитер»,
«Асьминог» вместо «осьминога», «Тетёртый» вместо «Четвёртый», а
шестой и седьмой пункты пропустил целиком. Замер на одном и том же
ролике:

    Whisper small     «Банкок», «Юбитер», «Неон» на месте «Ne»,
                      «братья в Карамазовых», знаков нет во второй
                      половине
    large-v3-turbo    лучше по именам, но втрое медленнее и знаки в
                      конце теряет так же
    Gemini            «Бангкок», «Юпитер», «Ne», «Братьев Карамазовых»,
                      знаки и заглавные по всему ролику

Чего у нейросети НЕТ — времён каждого слова. И это не беда: времена
готового ролика всё равно считаются заново по АНГЛИЙСКОЙ озвучке
(«озвучка.py» пишет их в раскадровку), а русские нужны только как
леса — чтобы разрезать текст на фразы и сохранить порядок. Поэтому
мы их рисуем сами, по длине слов. Порядок и границы предложений от
этого не страдают, а больше от русских времён ничего не зависит.

Тот же приём отвечает и на вторую просьбу — «хочу вставить текст без
видео»: текст приходит прямо от человека, времена рисуются точно так
же, и дальше конвейер не видит разницы.
"""
import base64
import io
import json
import os
import re
import sys
import urllib.request

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

HERE = os.path.dirname(os.path.abspath(__file__))

# Сколько «длится» слово, когда времена рисуем сами. Цифры взяты из
# настоящей расшифровки: 106 слов на 89 секунд — 0.84 секунды на слово,
# из них примерно треть приходится на паузы между фразами.
СЕКУНД_НА_ЗНАК = 0.055
МИНИМУМ = 0.22
ПАУЗА_ФРАЗЫ = 0.45

ЗАДАНИЕ = (
    "Запиши дословно всю русскую речь из этой записи.\n"
    "\n"
    "Это короткая видео-викторина: ведущий задаёт вопросы и сам же\n"
    "называет ответы.\n"
    "\n"
    "Правила:\n"
    "  - только текст речи, без пояснений, без тайм-кодов, без\n"
    "    подписей вроде «Диктор:»;\n"
    "  - расставь знаки препинания: вопрос закрывается «?», ответ —\n"
    "    точкой;\n"
    "  - имена собственные пиши правильно: Юпитер, Бангкок, Антарктида,\n"
    "    Ватикан. Если слышно неразборчиво — пиши самое осмысленное;\n"
    "  - ничего не пропускай и ничего не добавляй от себя. Если пункт\n"
    "    произнесён тихо или быстро — всё равно запиши его;\n"
    "  - ПИШИ РОВНО ТО, ЧТО ПРОИЗНЕСЕНО, даже если это фактически\n"
    "    неверно. Сказал ведущий «Юпитер» — пиши «Юпитер», хотя\n"
    "    правильный ответ Сатурн. Это запись чужой викторины, а не\n"
    "    проверка знаний: подменишь ответ — он разойдётся с картинкой\n"
    "    и с тем, что зритель слышит."
)


def слова_из_текста(текст, начало=0.0):
    """Текст -> список слов с нарисованными временами.

    Формат тот же, что у «subs.py»: {"w": слово, "a": начало, "b": конец}.
    """
    слова, время = [], float(начало)
    for кусок in текст.split():
        длина = max(МИНИМУМ, len(кусок) * СЕКУНД_НА_ЗНАК)
        слова.append({"w": кусок, "a": round(время, 2),
                      "b": round(время + длина, 2)})
        время += длина
        if кусок.rstrip("\"'»)").endswith((".", "!", "?", "…")):
            время += ПАУЗА_ФРАЗЫ
        else:
            время += 0.06
    return слова


def _ключ(имя):
    sys.path.insert(0, HERE)
    import проверить as пров
    return пров.key_file(имя)


def _гемини(звук, ключ, модель):
    тело = {"contents": [{"parts": [
        {"text": ЗАДАНИЕ},
        {"inline_data": {"mime_type": "audio/wav",
                         "data": base64.b64encode(звук).decode()}}]}],
        "generationConfig": {"temperature": 0}}
    адрес = ("https://generativelanguage.googleapis.com/v1beta/models/"
             "%s:generateContent?key=%s" % (модель, ключ))
    запрос = urllib.request.Request(
        адрес, data=json.dumps(тело).encode(),
        headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(запрос, timeout=600) as ответ:
        д = json.loads(ответ.read().decode("utf-8"))
    части = (д.get("candidates") or [{}])[0].get("content", {}).get("parts", [])
    return "".join(str(ч.get("text") or "") for ч in части).strip()


def _грок(звук, ключ, имя_файла="запись.wav"):
    """Groq крутит whisper-large-v3 — лучший бесплатный слух, если ключ есть."""
    граница = "----quiz10----"
    куски = []
    for поле, значение in (("model", "whisper-large-v3"),
                           ("language", "ru"),
                           ("response_format", "text")):
        куски.append(("--%s\r\nContent-Disposition: form-data; name=\"%s\""
                      "\r\n\r\n%s\r\n" % (граница, поле, значение)).encode())
    куски.append(("--%s\r\nContent-Disposition: form-data; name=\"file\";"
                  " filename=\"%s\"\r\nContent-Type: audio/wav\r\n\r\n"
                  % (граница, имя_файла)).encode())
    куски.append(звук)
    куски.append(("\r\n--%s--\r\n" % граница).encode())
    запрос = urllib.request.Request(
        "https://api.groq.com/openai/v1/audio/transcriptions",
        data=b"".join(куски),
        headers={"Authorization": "Bearer " + ключ,
                 "Content-Type": "multipart/form-data; boundary=" + граница})
    with urllib.request.urlopen(запрос, timeout=600) as ответ:
        return ответ.read().decode("utf-8").strip()


# Кого спрашиваем и в каком порядке. Groq первым: он крутит
# whisper-large-v3 и на нём же обучен слышать имена. Gemini вторым —
# ключ у нас есть всегда, и качество проверено на живом ролике.
СЛУШАТЕЛИ = (
    ("Groq (whisper-large-v3)", "ключ groq.txt",
     lambda звук, ключ: _грок(звук, ключ)),
    ("Gemini 3.6 Flash", "ключ gemini.txt",
     lambda звук, ключ: _гемини(звук, ключ, "gemini-3.6-flash")),
    ("Gemini 3 Flash", "ключ gemini.txt",
     lambda звук, ключ: _гемини(звук, ключ, "gemini-3-flash-preview")),
)


def нейросетью(wav):
    """Возвращает (текст, кто слушал). Пусто — никто не смог."""
    звук = io.open(wav, "rb").read()
    мб = len(звук) / 1024 / 1024
    for имя, файл_ключа, зов in СЛУШАТЕЛИ:
        ключ = _ключ(файл_ключа)
        if not ключ:
            continue
        print("Слушает %s (%.1f МБ)..." % (имя, мб))
        try:
            текст = зов(звук, ключ)
        except Exception as е:
            подробности = ""
            try:
                подробности = е.read().decode("utf-8", "replace")[:160]
            except Exception:
                pass
            print("   не вышло: %s %s" % (е, подробности))
            continue
        текст = re.sub(r"\s+", " ", текст or "").strip()
        # Пустой или подозрительно короткий ответ — это не расшифровка.
        if len(текст.split()) < 10:
            print("   ответил слишком коротко (%d слов) — беру следующего."
                  % len(текст.split()))
            continue
        print("   расслышано слов: %d" % len(текст.split()))
        return текст, имя
    return "", ""
