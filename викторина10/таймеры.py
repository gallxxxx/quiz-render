# -*- coding: utf-8 -*-
r"""
Показывает русский текст ролика: где встанут таймеры и всё ли расслышано.

Запуск:  python таймеры.py             (показать, дождаться, забрать правки)
         python таймеры.py --показать  (только написать файл)
         python таймеры.py --забрать   (только прочитать правки)
         python таймеры.py --применить (вернуть «Т» в свежую раскадровку)

Зачем. Таймеры скрипт расставляет сам, но глазами это никак не
проверить: раскадровка английская, а на слух ролик русский. Здесь
русский текст показывается как есть, и перед фразой, на которой
кончится шкала таймера, стоит «Т».

Правило простое: «Т» стоит перед ВСЕЙ ФРАЗОЙ-ОТВЕТОМ — то есть перед
словом «ответ», а не после него. Шкала кончается там, где стоит «Т»,
и «Ответ: Япония» целиком звучит уже после таймера.

Если слова «ответ» в ролике нет вообще («Первая марка — это Мерседес»),
«Т» встаёт прямо перед названием.

ТЕКСТ ТОЖЕ МОЖНО ПРАВИТЬ. Это тот же текст, который переводится и
озвучивается, — если Whisper расслышал «Калибры» вместо «Колибри»,
слово исправляется прямо здесь. Времена при этом не теряются: старый
и новый текст сличаются пословно, и каждое слово получает свою секунду
(правленые — от того куска, на месте которого стоят). Изменил текст —
скрипт перепишет расшифровку, а «всё.py» заново переведёт ролик,
пересчитает ответы и вернёт таймеры на место.

Буква «Т» — только метка. В перевод и в озвучку она не попадает:
переводчик выбрасывает её до отправки (см. «перевод.py», strip_marks).
"""
import difflib, io, json, os, re, subprocess, sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

import папки

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = папки.work("out")
BOARD = папки.work("раскадровка.txt")
FILE = папки.work(os.path.join("out", "ПРОВЕРЬ ТАЙМЕРЫ.txt"))
СЕКУНДЫ = папки.work(os.path.join("out", "_секунды таймеров.txt"))
ОТВЕТЫ_ФАЙЛ = папки.work(os.path.join("out", "_ответы из кавычек.json"))
MARK = "Т"

# Слова, которые говорят перед ответом: «правильный ответ», «верный ответ».
# Шкала должна кончиться до них, а не посреди фразы.
ВВОДНЫЕ = ("правильный", "правильная", "правильные", "верный", "верная")

ШАПКА = [
    "# ГДЕ БУДУТ ТАЙМЕРЫ И ВСЁ ЛИ РАССЛЫШАНО",
    "#",
    "# На букве «Т» шкала таймера доходит до конца. Всё, что после «Т»,",
    "# говорится уже без шкалы — поэтому «Т» стоит перед всей фразой",
    "# с ответом («Т Ответ «Япония»»), а не между «Ответ» и названием.",
    "#",
    "# «Т» можно передвинуть к другому слову, удалить лишнюю, дописать новую.",
    "#",
    "# САМ ОТВЕТ СТОИТ В КАВЫЧКАХ «ВОТ ТАК». Кавычки — не украшение:",
    "# по ним видно, что пойдёт в кадр списком, и переводчик понимает,",
    "# что это название, а не обычное слово (без них «Лев» становится",
    "# зверем, а «Орёл» птицей). Ответ услышан неверно или взят не тот —",
    "# передвинь кавычки или поправь слово внутри них.",
    "#",
    "# ТЕКСТ ТОЖЕ МОЖНО ПРАВИТЬ. Это тот самый текст, который переведут",
    "# и озвучат. Расслышано неверно — исправь слово прямо здесь, лишнее",
    "# сотри, пропущенное допиши. Времена не потеряются.",
    "# Каждое предложение — своей строкой, так виднее, где что.",
    "#",
    "# Сохрани (Ctrl+S) и закрой это окно — сборка пойдёт дальше.",
    "",
]

# Кавычки вокруг ответа. Открывающая и закрывающая — разные, чтобы при
# чтении обратно было видно, где ответ начался и где кончился.
КАВЫЧКИ = ("«", "»")
ВСЕ_КАВЫЧКИ = "«»\"„“”"

# После этих слов звучит ответ. Тот же список, что в «ответы.py»:
# разметка в этом файле и поиск ответов должны понимать текст одинаково.
МАРКЕРЫ = ("ответ", "ответы", "отвечаю")
ХВОСТ = 4                    # сколько слов после маркера считаем ответом
# Слова, на которых ответ заведомо кончился: пошла следующая мысль.
# Порядковые здесь не для красоты: когда знаки препинания не расставлены,
# ведущий говорит «правильный ответ Ватикан третий вопрос какая...» —
# и без них в кадр уезжает «Ватикан третий».
ПОРЯДКОВЫЕ = ("первый", "второй", "третий", "четвертый", "четвёртый",
              "пятый", "шестой", "седьмой", "восьмой", "девятый",
              "десятый", "следующий", "далее")
СТОП_СЛОВА = ("вопрос", "лайк", "поставь", "отправь", "продолжаем",
              "напиши", "подпишись", "страна", "марка", "номер",
              "пиши", "комментариях", "комментарии", "сколько",
              "угадал", "правильных") + ПОРЯДКОВЫЕ


def newest(ext):
    files = [f for f in os.listdir(OUT_DIR) if f.endswith(ext)] \
        if os.path.isdir(OUT_DIR) else []
    if not files:
        return None
    files.sort(key=lambda f: os.path.getmtime(os.path.join(OUT_DIR, f)),
               reverse=True)
    return files[0][:-len(ext)]


def имя_ролика():
    return newest(".слова.json")


def words():
    """Русские слова с временами — их пишет subs.py."""
    name = имя_ролика()
    if not name:
        return []
    p = os.path.join(OUT_DIR, name + ".слова.json")
    if not os.path.exists(p):
        return []
    return json.load(io.open(p, encoding="utf-8"))


def board_times():
    """Секунды ответов из раскадровки — вокруг них и стоят таймеры."""
    if not os.path.exists(BOARD):
        return []
    out = []
    for raw in io.open(BOARD, encoding="utf-8-sig"):
        s = raw.strip()
        if not s or s.startswith("#") or "|" not in s:
            continue
        if re.match(r"^(?:ТЕМА|TITLE)\s*:", s, re.I):
            continue
        m = re.match(r"^\s*(\d+):(\d+(?:\.\d+)?)", s)
        if m:
            out.append(int(m.group(1)) * 60 + float(m.group(2)))
    return sorted(out)


def норм(слово):
    """Слово без знаков и регистра — для сличения старого текста с новым."""
    return re.sub(r"[^а-яёa-z0-9]", "", str(слово or "").lower())


def показать():
    ws = words()
    if not ws:
        sys.exit("Нет файла «...слова.json» — сначала распознай речь.")
    times = board_times()
    if not times:
        sys.exit("В «раскадровка.txt» нет ответов — сначала кнопка 2.")

    # Где ответ. Сначала по слову «ответ»: ведущий почти всегда говорит
    # «ответ» перед тем, как назвать его. Это надёжнее времён из
    # раскадровки — те после озвучки пересчитываются под английскую
    # речь и с русскими словами уже не совпадают.
    #
    # «Т» встаёт ПЕРЕД словом «ответ», а не после него: шкала кончается
    # на «Т», и вся фраза «Ответ: Япония» звучит уже после таймера.
    # Раньше «Т» стояла между «Ответ» и названием — слово «Ответ»
    # оставалось под работающей шкалой, а пауза резала фразу пополам.
    метки = set()
    for i, w in enumerate(ws):
        слово = re.sub(r"[^а-яёa-z]", "", str(w.get("w") or "").lower())
        if слово not in ("ответ", "ответы"):
            continue
        # после «ответ» должно идти хоть одно слово — иначе это не разметка
        j = i + 1
        while j < len(ws):
            if норм(ws[j].get("w")):
                break
            j += 1
        if j >= len(ws):
            continue
        # «правильный ответ» — вводное целиком, отходим и на него
        k = i
        while k > 0 and re.sub(r"[^а-яё]", "",
                               str(ws[k - 1].get("w") or "").lower()) in ВВОДНЫЕ:
            k -= 1
        if k > 0:
            метки.add(k)

    # Ответов оказалось не столько, сколько в раскадровке, — значит
    # «ответ» вслух звучит не всегда. Добираем по времени.
    if len(метки) < len(times):
        for t in times:
            лучший, разница = None, None
            for i, w in enumerate(ws):
                d = abs(float(w["b"]) - t)
                if разница is None or d < разница:
                    лучший, разница = i, d
            if (лучший is not None and разница is not None
                    and разница < 3.0 and лучший not in метки):
                метки.add(лучший)

    ответы = найти_ответы(ws)

    # Разбиваем на строки по ПРЕДЛОЖЕНИЯМ: знаки препинания к этому
    # времени уже расставлены («знаки.py»), и по ним текст читается
    # ровно так, как его услышит зритель. Если знаков вдруг нет совсем
    # (нейросеть не ответила), остаётся прежний путь — по паузам речи.
    по_знакам = sum(1 for w in ws
                    if str(w.get("w") or "").rstrip().endswith((".", "!", "?")))
    строки, текущая, прошлый_конец, конец_фразы = [], [], None, False
    for i, w in enumerate(ws):
        рвём = конец_фразы if по_знакам >= 3 else prev_break(
            prev_end=прошлый_конец, начало=float(w["a"]))
        if рвём and текущая:
            строки.append(текущая)
            текущая = []
        if i in метки:
            текущая.append(MARK)
        слово = str(w.get("w") or w.get("word") or "").strip()
        # Ответ берём в кавычки: это и подсказка человеку, что попадёт
        # в кадр, и защита перевода — слово в кавычках переводчик
        # понимает как название, а не как обычное существительное.
        if i in ответы:
            начало_о, конец_о = ответы[i]
            if начало_о:
                слово = КАВЫЧКИ[0] + слово
            if конец_о:
                хвост = ""
                while слово and слово[-1] in ".,!?;:":
                    хвост = слово[-1] + хвост
                    слово = слово[:-1]
                слово = слово + КАВЫЧКИ[1] + хвост
        текущая.append(слово)
        прошлый_конец = float(w["b"])
        конец_фразы = str(w.get("w") or "").rstrip().endswith((".", "!", "?"))
        # «Ответ.» и сам ответ — одна фраза, даже если между ними точка:
        # нейросеть ставит её охотно, а разорванное «Т Ответ.» / «Россия»
        # читается так, будто таймер стоит не там, где стоит.
        if конец_фразы and (i + 1) in ответы and ответы[i + 1][0]:
            конец_фразы = False
    if текущая:
        строки.append(текущая)

    io.open(FILE, "w", encoding="utf-8", newline="\r\n").write(
        "\n".join(ШАПКА + [" ".join(s) for s in строки]) + "\n")
    print("Написал: %s" % os.path.basename(FILE))
    print("Таймеров отмечено: %d" % len(метки))
    print("Ответов в кавычках: %d" % sum(1 for v in ответы.values() if v[0]))
    return len(метки)


def найти_ответы(ws):
    """Какие слова — сам ответ. Возвращает {номер слова: (начало, конец)}.

    Ищем так же, как «ответы.py»: после слова «ответ» идёт короткое
    название, до ближайшего знака препинания, но не длиннее четырёх слов.
    Границы нужны обе: ответ бывает из двух слов («Южная Корея»), и
    закрывающая кавычка должна встать после последнего, иначе переводчик
    получит половину названия.
    """
    ответы = {}
    i = 0
    while i < len(ws):
        сырое = str(ws[i].get("w") or "")
        чистое = re.sub(r"[^а-яёa-z]", "", сырое.lower())
        if чистое not in МАРКЕРЫ:
            i += 1
            continue
        куски = []
        for j in range(i + 1, min(i + 1 + ХВОСТ, len(ws))):
            слово = str(ws[j].get("w") or "").strip()
            голое = слово.strip(".,!?;:" + ВСЕ_КАВЫЧКИ)
            # Ведущий говорит «правильный ответ — Ватикан», и тире
            # расслышивается отдельным словом. В ответ оно попадать не
            # должно: в кадре стояло бы «– Ватикан».
            if not голое or re.sub(r"[—–\-]", "", голое) == "":
                continue
            if re.sub(r"[^а-яё]", "", голое.lower()) in СТОП_СЛОВА:
                break
            куски.append(j)
            if слово.endswith((".", "!", "?", ",", ";", ":", "—", "-")):
                break
        # В ответ влезает номер следующего пункта: «Ответ голубая 7»,
        # «Северный Ледовитый 6», «Кожа 9», «Меркурий 10». Раньше цифру
        # отбрасывали, только если следом шло стоп-слово, — а следом
        # обычно идёт сам вопрос («Какая кровь...»), и номер оставался
        # в кадре.
        #
        # Теперь проще и надёжнее: у ответа ИЗ НЕСКОЛЬКИХ СЛОВ голая
        # цифра до десяти на конце — это номер пункта, а не часть
        # ответа. Ответ-число («8», «7», «Три») не трогаем: там цифра
        # единственное слово. «Аполлон 11» уцелеет — одиннадцать больше
        # десяти; сломается только «Формула 1», и это видно в окне
        # проверки.
        while len(куски) > 1:
            хвост = str(ws[куски[-1]].get("w") or "").strip(".,!?;:")
            if re.fullmatch(r"\d{1,2}", хвост) and int(хвост) <= 10:
                куски.pop()
                continue
            break
        if куски:
            for n, j in enumerate(куски):
                ответы[j] = (n == 0, n == len(куски) - 1)
            i = куски[-1] + 1
        else:
            i += 1
    return ответы


def prev_break(prev_end, начало, пауза=0.6):
    return prev_end is not None and начало - prev_end >= пауза


def прочитать_файл():
    """Из блокнота — поток слов, места «Т» и что человек взял в кавычки.

    «места» — номера слов, ПЕРЕД которыми стояла «Т».
    «ответы» — номера слов, оказавшихся внутри кавычек. Сами кавычки в
    текст не возвращаются: они разметка, а не часть речи, и диктор не
    должен их читать. Зато по ним мы точно знаем, что человек считает
    ответом, — это надёжнее любого поиска по словарю.
    """
    слова, места, ответы = [], [], []
    внутри = False
    for raw in io.open(FILE, encoding="utf-8-sig"):
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        for кусок in s.split():
            if кусок.strip(".,!?;:" + ВСЕ_КАВЫЧКИ).upper() in (MARK, "T"):
                места.append(len(слова))
                continue
            открылась = кусок.lstrip(".,!?;:").startswith(tuple(ВСЕ_КАВЫЧКИ))
            голое = кусок
            for знак in ВСЕ_КАВЫЧКИ:
                голое = голое.replace(знак, "")
            закрылась = голое != кусок and not открылась
            # Кавычка может открыться и закрыться на одном слове: «Япония».
            обе = кусок.count("«") and кусок.count("»")
            if открылась or внутри or обе:
                if голое.strip(".,!?;:"):
                    ответы.append(len(слова))
            if обе:
                внутри = False
            elif открылась:
                внутри = True
            elif закрылась:
                внутри = False
            if голое:
                слова.append(голое)
    return слова, места, ответы


def пересобрать(ws, новые):
    """Слова из блокнота + времена из расшифровки.

    Текст в файле можно править, а времена терять нельзя — по ним стоит
    вообще всё: и таймеры, и субтитры, и порядок карточек. Сличаем два
    списка слов difflib'ом и раздаём времена по кускам:

      совпало   — время как было, написание берём новое (там могли
                  поправить только знак препинания);
      заменено  — время старого куска делим поровну между новыми словами;
      дописано  — вставляем в щель между соседями, а нет щели —
                  отщипываем по 0.4 секунды;
      удалено   — выбрасываем вместе со временем.
    """
    старые_н = [норм(w.get("w")) for w in ws]
    новые_н = [норм(x) for x in новые]
    out = []

    def раздать(a0, a1, b0, b1):
        сколько = b1 - b0
        if сколько <= 0:
            return
        if a1 > a0:                       # на месте старого куска
            начало = float(ws[a0]["a"])
            конец = float(ws[a1 - 1]["b"])
        else:                             # чистая вставка: щель между соседями
            начало = float(ws[a0 - 1]["b"]) if a0 > 0 else 0.0
            конец = float(ws[a0]["a"]) if a0 < len(ws) else начало
        if конец <= начало:
            конец = начало + 0.4 * сколько
        шаг = (конец - начало) / сколько
        for k in range(сколько):
            out.append({"w": новые[b0 + k],
                        "a": round(начало + шаг * k, 3),
                        "b": round(начало + шаг * (k + 1), 3)})

    сличение = difflib.SequenceMatcher(None, старые_н, новые_н, autojunk=False)
    for tag, a0, a1, b0, b1 in сличение.get_opcodes():
        if tag == "equal":
            for k in range(a1 - a0):
                w = dict(ws[a0 + k])
                w["w"] = новые[b0 + k]
                out.append(w)
        elif tag == "delete":
            continue
        else:                             # replace / insert
            раздать(a0, a1, b0, b1)
    return out


def сохранить(name, слова_):
    """Переписываем расшифровку — ровно так же, как это делает subs.py."""
    sys.path.insert(0, HERE)
    import subs
    io.open(os.path.join(OUT_DIR, name + ".слова.json"), "w",
            encoding="utf-8").write(
        json.dumps(слова_, ensure_ascii=False, indent=1))
    io.open(os.path.join(OUT_DIR, name + ".ru.txt"), "w",
            encoding="utf-8").write(" ".join(w["w"] for w in слова_))
    subs.write_phrases(subs.phrases(слова_),
                       os.path.join(OUT_DIR, name + ".русский.txt"))


def записать_времена(времена):
    """Секунды «Т» -> строки раскадровки.

    «Т» бывает больше, чем строк: слово «ответ» звучит и там, где ответ
    не распознался («???»). Раздавать по порядку нельзя — времена
    съезжают на соседние строки, и карточки выскакивают не в свой момент.
    Каждой строке достаётся БЛИЖАЙШАЯ по времени «Т», и порядок при этом
    не нарушается: у следующей строки таймер не может быть раньше.
    """
    if not времена or not os.path.exists(BOARD):
        return 0
    строки = io.open(BOARD, encoding="utf-8-sig").read() \
        .replace("\r\n", "\n").split("\n")
    ряды = []                             # (номер строки, секунда, ответ)
    for n, s in enumerate(строки):
        t = s.strip()
        if (not t or t.startswith("#") or "|" not in t
                or re.match(r"^(?:ТЕМА|TITLE)\s*:", t, re.I)):
            continue
        левое, правое = t.split("|", 1)
        m = re.match(r"^\s*(\d+):(\d+(?:\.\d+)?)\s*$", левое.strip())
        if not m:
            continue
        ряды.append((n, int(m.group(1)) * 60 + float(m.group(2)),
                     правое.strip()))
    if not ряды:
        return 0

    с, поставлено = 0, 0
    for k, (n, было, ответ) in enumerate(ряды):
        осталось = len(ряды) - k - 1
        предел = len(времена) - осталось   # дальше нельзя: не хватит хвоста
        лучший, разница = None, None
        for j in range(с, max(с + 1, предел)):
            if j >= len(времена):
                break
            d = abs(времена[j] - было)
            if разница is None or d < разница:
                лучший, разница = j, d
        if лучший is None:
            break
        сек = времена[лучший]
        строки[n] = "%d:%04.1f | %s" % (int(сек // 60), сек % 60, ответ)
        с = лучший + 1
        поставлено += 1
    io.open(BOARD, "w", encoding="utf-8", newline="\r\n").write(
        "\n".join(строки) + "\n")
    return поставлено


def запомнить(времена):
    io.open(СЕКУНДЫ, "w", encoding="utf-8").write(
        "\n".join("%.3f" % t for t in времена) + "\n")


def вспомнить():
    if not os.path.exists(СЕКУНДЫ):
        return []
    out = []
    for raw in io.open(СЕКУНДЫ, encoding="utf-8-sig"):
        raw = raw.strip()
        if raw:
            try:
                out.append(float(raw))
            except ValueError:
                pass
    return out


def забрать():
    """Читаем правки: где теперь «Т» и не поменялся ли сам текст."""
    if not os.path.exists(FILE):
        return 0
    ws = words()
    name = имя_ролика()
    if not ws or not name:
        return 0

    новые, места, ответы = прочитать_файл()
    if not новые:
        print("Файл пустой — ничего не трогаю.")
        return 0

    менялся = [str(w.get("w") or "") for w in ws] != новые
    ws2 = пересобрать(ws, новые)
    if менялся:
        сохранить(name, ws2)
        print("Текст поправлен: слов было %d, стало %d." % (len(ws), len(ws2)))
        print("Расшифровка переписана — ролик переведу заново.")

    # Что человек оставил в кавычках — то и есть ответы. Кладём рядом
    # готовыми строками со временем: «ответы.py» возьмёт их вместо
    # поиска по словарю, и «???» в раскадровке взяться уже неоткуда.
    записать_ответы(ws2, ответы)

    if not места:
        print("Ни одной «Т» не осталось — таймеры не трогаю.")
        return 0

    времена = [float(ws2[i]["b"]) for i in места if 0 <= i < len(ws2)]
    if not времена:
        return 0
    запомнить(времена)
    поставлено = записать_времена(времена)
    print("Забрал %d таймер(ов), вписал в раскадровку: %d."
          % (len(времена), поставлено))
    return len(времена)


def записать_ответы(ws, номера):
    """Ответы из кавычек — в «out\\_ответы из кавычек.json».

    Соседние номера склеиваем в одну строку: «Южная Корея» — это один
    ответ из двух слов, а не два. Время берём по последнему слову:
    пункт должен выскочить, когда его договорили.
    """
    if not номера:
        if os.path.exists(ОТВЕТЫ_ФАЙЛ):
            os.remove(ОТВЕТЫ_ФАЙЛ)     # кавычки стёрли — разметки больше нет
        return 0
    куски, текущий = [], []
    for n in sorted(set(номера)):
        if 0 <= n < len(ws):
            if текущий and n != текущий[-1] + 1:
                куски.append(текущий)
                текущий = []
            текущий.append(n)
    if текущий:
        куски.append(текущий)

    готовое = []
    for кусок in куски:
        слова_ = [str(ws[i].get("w") or "").strip(".,!?;:" + ВСЕ_КАВЫЧКИ)
                  for i in кусок]
        слова_ = [с for с in слова_ if с]
        if not слова_:
            continue
        готовое.append({"rus": " ".join(слова_),
                        "t": float(ws[кусок[-1]]["b"])})
    io.open(ОТВЕТЫ_ФАЙЛ, "w", encoding="utf-8").write(
        json.dumps(готовое, ensure_ascii=False, indent=1))
    print("Ответов из кавычек: %d" % len(готовое))
    return len(готовое)


def применить():
    """Вписать запомненные «Т» в свежую раскадровку.

    Нужно после правки текста: «всё.py» заново переводит ролик и заново
    ищет ответы, раскадровка получается новая — и таймеры, расставленные
    в блокноте, надо вернуть на место.
    """
    времена = вспомнить()
